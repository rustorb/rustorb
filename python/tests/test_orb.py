    def test_servant_activator(self):
        events = []

        class Activator(PortableServer__POA.ServantActivator):
            def incarnate(self, oid, adapter):
                events.append(("incarnate", oid, adapter.the_name))
                if oid == b"forward":
                    raise PortableServer.ForwardRequest(target)
                if oid == b"missing":
                    raise CORBA.OBJECT_NOT_EXIST(0, CORBA.COMPLETED_NO)
                return make_echo_servant()

            def etherealize(self, oid, adapter, servant, cleanup, remaining):
                events.append(("etherealize", oid, cleanup, remaining))

        root = self.root
        target = root.servant_to_reference(make_echo_servant())
        poa = root.create_POA(
            "activated",
            root._get_the_POAManager(),
            [
                root.create_id_assignment_policy(PortableServer.USER_ID),
                root.create_request_processing_policy(PortableServer.USE_SERVANT_MANAGER),
            ],
        )
        activator = Activator()
        poa.set_servant_manager(activator)
        self.assertIs(poa.get_servant_manager(), activator)
        ref = remote(client_orb, poa.create_reference_with_id(b"x", T.Echo._NP_RepositoryId), T.Echo)
        self.assertEqual(ref.echo_long(1), 1)
        self.assertEqual(ref.echo_long(2), 2)
        self.assertEqual(events, [("incarnate", b"x", "activated")])
        fwd = remote(client_orb, poa.create_reference_with_id(b"forward", T.Echo._NP_RepositoryId), T.Echo)
        self.assertEqual(fwd.echo_long(3), 3)
        missing = remote(client_orb, poa.create_reference_with_id(b"missing", T.Echo._NP_RepositoryId), T.Echo)
        with self.assertRaises(CORBA.OBJECT_NOT_EXIST):
            missing.echo_long(4)
        poa.destroy(True, True)
        self.assertIn(("etherealize", b"x", True, False), events)

