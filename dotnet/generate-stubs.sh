#!/usr/bin/env bash
# Regenerates the stubs of the runtime in src/Rustorb.Corba with rustorb-idl
# -bcsharp: CosNaming (from tests/mapping/idl/CosNaming.idl) and
# Messaging::ReplyHandler of callback AMI (Messaging.ExceptionHolder is
# written by hand, in Rustorb/Ami.cs). Needs
# rustorb-idl importable (tools/rustorb-idl.txt), or RUSTORB_IDL_DIR set to a
# checkout of it (and IDL_PARSER_DIR to one of idl_parser). CI checks that
# the committed stubs are up to date (it runs this and git diff).
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
root="$here/.."
out="${1:-$here/src/Rustorb.Corba/CosNaming}"
pythonpath="${RUSTORB_IDL_DIR:+$RUSTORB_IDL_DIR/python}"
[ -n "${IDL_PARSER_DIR:-}" ] && pythonpath="$IDL_PARSER_DIR${pythonpath:+:$pythonpath}"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
PYTHONPATH="$pythonpath${PYTHONPATH:+${pythonpath:+:}$PYTHONPATH}" python3 -m rustorb_idl -bcsharp \
  -C "$tmp" "$root/tests/mapping/idl/CosNaming.idl"
mkdir -p "$out"
cp "$tmp/CosNaming.cs" "$out/CosNaming.g.cs"
if [ -z "${1:-}" ]; then
  cat > "$tmp/Messaging.idl" <<'IDL'
// Messaging::ReplyHandler (rustorb-idl's Messaging.idl, without the
// ExceptionHolder valuetype).
#pragma prefix "omg.org"
module Messaging {
  interface ReplyHandler {};
};
IDL
  PYTHONPATH="$pythonpath${PYTHONPATH:+${pythonpath:+:}$PYTHONPATH}" python3 -m rustorb_idl -bcsharp \
    -C "$tmp" "$tmp/Messaging.idl"
  mkdir -p "$here/src/Rustorb.Corba/Messaging"
  sed 's|Generated by rustorb-idl from Messaging.idl|Generated by rustorb-idl from Messaging::ReplyHandler (generate-stubs.sh)|' \
    "$tmp/Messaging.cs" > "$here/src/Rustorb.Corba/Messaging/ReplyHandler.g.cs"
fi
