"""Runs rtshell (rtls, rtcat, rtcon, rtact, rtdeact, rtdis, rtconf, rtexit)
on rustorb (through the omniORBpy compatibility package) or on omniORBpy,
against the SimpleIO RTCs of OpenRTM-aist-Python on rustorb or omniORBpy,
or of OpenRTM-aist (C++), and checks what the commands print and do.

    rtshell.py --openrtm DIR --rustorb DIR --compat DIR --rustorb-stubs DIR
               --omniorbpy DIR --omniorbpy-stubs DIR --rtshell DIR
               --rtctree-rustorb DIR --rtctree-omniorbpy DIR --out DIR
               [--cxx-examples DIR] [--naming CMD] [--python PY] [--port N]

--rtshell is the source tree of rtshell (the commands run here do not use
rtsprofile).
--rtctree-rustorb and --rtctree-omniorbpy each hold a copy of the rtctree
package with its stubs (rtctree.rtc) generated by rustorb-idl and omniidl
with -Wbpackage=rtctree.rtc. The naming service is started as in
scenarios.py.
"""

import argparse
import os
import re
import signal
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from scenarios import PY_IMPLS  # noqa: E402

IN, OUT = "/localhost/ConsoleIn0.rtc", "/localhost/ConsoleOut0.rtc"


class Failed(Exception):
    pass


class Runner(object):
    def __init__(self, args):
        self.args = args
        self.python = args.python
        openrtm = os.path.abspath(args.openrtm)
        self.examples = os.path.join(openrtm, "OpenRTM_aist", "examples")
        common = [openrtm, os.path.join(openrtm, "OpenRTM_aist"),
                  os.path.join(openrtm, "OpenRTM_aist", "utils")]
        self.rtc_paths = {
            "rustorb": [args.compat, args.rustorb, args.rustorb_stubs] + common,
            "omniorbpy": [args.omniorbpy, args.omniorbpy_stubs] + common,
        }
        self.shell_paths = {
            "rustorb": [args.rtctree_rustorb, args.rtshell] + self.rtc_paths["rustorb"],
            "omniorbpy": [args.rtctree_omniorbpy, args.rtshell] + self.rtc_paths["omniorbpy"],
        }
        self.cxx = args.cxx_examples and os.path.abspath(args.cxx_examples)
        self.out = os.path.abspath(args.out)
        os.makedirs(os.path.join(self.out, "logs"), exist_ok=True)
        self.conf = os.path.join(self.out, "rtshell.conf")
        with open(self.conf, "w") as f:
            f.write("corba.nameservers: localhost:%d\n" % args.port)
            f.write("naming.formats: %n.rtc\nlogger.enable: NO\n")
        self.env_base = dict(os.environ, PYTHONUNBUFFERED="1")
        self.log = None

    def env(self, paths):
        env = dict(self.env_base)
        env["PYTHONPATH"] = os.pathsep.join(os.path.abspath(p) for p in paths)
        return env

    def start_rtc(self, impl, which, log, stdin):
        cwd = os.path.join(self.examples, "SimpleIO")
        if impl == "cxx":
            argv, env = [os.path.join(self.cxx, which + "Comp")], self.env_base
        else:
            argv, env = [self.python, which + ".py"], self.env(self.rtc_paths[impl])
        return subprocess.Popen(argv + ["-f", self.conf], cwd=cwd, env=env, stdin=stdin,
                                stdout=log, stderr=subprocess.STDOUT, start_new_session=True)

    def rt(self, shell, cmd, *args, **kw):
        """Runs an rtshell command; returns its output."""
        code = ("import sys; from rtshell import %s as m; "
                "sys.argv = [%r] + sys.argv[1:]; sys.exit(m.main())" % (cmd, cmd))
        p = subprocess.run([self.python, "-c", code] + list(args),
                           env=self.env(self.shell_paths[shell]), stdout=subprocess.PIPE,
                           stderr=subprocess.STDOUT, universal_newlines=True, timeout=60)
        self.log.write("$ %s %s\n%s[rc=%d]\n" % (cmd, " ".join(args), p.stdout, p.returncode))
        self.log.flush()
        if p.returncode != kw.get("rc", 0):
            raise Failed("%s %s: exit status %d" % (cmd, " ".join(args), p.returncode))
        return p.stdout

    def expect(self, what, ok):
        if not ok:
            raise Failed(what)

    def states(self, shell):
        """{name: state} from rtls -l."""
        out = self.rt(shell, "rtls", "-l", "/localhost")
        return {m.group(2): m.group(1)
                for m in re.finditer(r"^(\w+)\s+.*\s(\S+\.rtc)$", out, re.M)}

    def wait_names(self, shell, names):
        for _ in range(50):
            out = self.rt(shell, "rtls", "/localhost")
            if set(names) <= set(out.split()):
                return
            time.sleep(0.2)
        raise Failed("rtls does not list %s" % " ".join(names))

    def run(self, rtc_impl, shell):
        tag = "rtshell-%s-%s" % (rtc_impl, shell)
        logs = os.path.join(self.out, "logs")
        in_log = open(os.path.join(logs, tag + "-in.log"), "w")
        out_log_path = os.path.join(logs, tag + "-out.log")
        out_log = open(out_log_path, "w")
        self.log = open(os.path.join(logs, tag + ".log"), "w")
        numbers = os.path.join(self.out, "rtshell-numbers.in")
        with open(numbers, "w") as f:
            f.write("".join("%d\n" % i for i in range(1, 100001)))
        procs = []
        try:
            with open(numbers) as stdin:
                procs.append(self.start_rtc(rtc_impl, "ConsoleIn", in_log, stdin))
            procs.append(self.start_rtc(rtc_impl, "ConsoleOut", out_log, subprocess.DEVNULL))
            self.wait_names(shell, ["ConsoleIn0.rtc", "ConsoleOut0.rtc"])

            out = self.rt(shell, "rtcat", OUT)
            self.expect("rtcat: profile", re.search(r"^ConsoleOut0\.rtc\s+Inactive", out, re.M)
                        and re.search(r"^\s*Type name\s+ConsoleOut$", out, re.M)
                        and "DataInPort: in" in out)
            self.expect("rtconf: configuration sets",
                        "default" in self.rt(shell, "rtconf", OUT, "list"))
            self.rt(shell, "rtcon", IN + ":out", OUT + ":in")
            self.expect("rtcat -l: connection", "Connected to  %s:in" % OUT
                        in self.rt(shell, "rtcat", "-l", IN + ":out"))

            self.rt(shell, "rtact", IN, OUT)
            st = self.states(shell)
            self.expect("rtls -l after rtact: %r" % st,
                        st.get("ConsoleIn0.rtc") == st.get("ConsoleOut0.rtc") == "Active")
            time.sleep(2)
            self.rt(shell, "rtdeact", IN, OUT)
            st = self.states(shell)
            # The C++ ConsoleIn goes to the error state when deactivated (with
            # rtshell on omniORBpy as well).
            in_states = ("Inactive", "Error") if rtc_impl == "cxx" else ("Inactive",)
            self.expect("rtls -l after rtdeact: %r" % st,
                        st.get("ConsoleIn0.rtc") in in_states
                        and st.get("ConsoleOut0.rtc") == "Inactive")
            with open(out_log_path, errors="replace") as f:
                received = len(re.findall(r"^Received:\s+\d+$", f.read(), re.M))
            self.expect("ConsoleOut received %d values" % received, received >= 5)

            self.rt(shell, "rtdis", IN + ":out")
            self.expect("rtcat -l after rtdis: still connected",
                        "Connected to" not in self.rt(shell, "rtcat", "-l", IN + ":out"))

            # rtexit makes ConsoleOut exit (and unbind its name).
            self.rt(shell, "rtexit", OUT)
            try:
                procs[1].wait(15)
            except subprocess.TimeoutExpired:
                raise Failed("ConsoleOut did not exit after rtexit")

            # A process killed without unbinding leaves a zombie: rtls shows it
            # with a "*" (rtctree tells it by the TRANSIENT of a failed
            # connection).
            os.killpg(procs[0].pid, signal.SIGKILL)
            procs[0].wait()
            out = self.rt(shell, "rtls", "/localhost")
            self.expect("rtls after the kill: %r" % out, "*ConsoleIn0.rtc" in out.split())
        finally:
            for p in procs:
                try:
                    os.killpg(p.pid, signal.SIGTERM)
                except OSError:
                    pass
            for p in procs:
                try:
                    p.wait(10)
                except subprocess.TimeoutExpired:
                    os.killpg(p.pid, signal.SIGKILL)
                    p.wait()
            for f in (in_log, out_log, self.log):
                f.close()


def main():
    ap = argparse.ArgumentParser()
    for opt in ("openrtm", "rustorb", "compat", "rustorb-stubs", "omniorbpy",
                "omniorbpy-stubs", "rtshell", "rtctree-rustorb",
                "rtctree-omniorbpy", "out"):
        ap.add_argument("--" + opt, required=True)
    ap.add_argument("--cxx-examples", help="the directory of OpenRTM-aist's example executables")
    ap.add_argument("--naming", default="omniNames -start {port} -logdir {dir}",
                    help="the command line of the naming service")
    ap.add_argument("--python", default=sys.executable)
    ap.add_argument("--port", type=int, default=2809)
    args = ap.parse_args()

    runner = Runner(args)
    naming_dir = os.path.join(runner.out, "naming-rtshell")
    os.makedirs(naming_dir, exist_ok=True)
    for f in os.listdir(naming_dir):
        os.remove(os.path.join(naming_dir, f))
    naming_log = open(os.path.join(runner.out, "logs", "naming-rtshell.log"), "w")
    naming = subprocess.Popen(
        [a.format(port=args.port, dir=naming_dir) for a in args.naming.split()],
        stdout=naming_log, stderr=subprocess.STDOUT,
    )
    # RTCs on each ORB with rtshell on rustorb, and rtshell on omniORBpy with
    # RTCs on rustorb.
    combos = [(impl, "rustorb") for impl in PY_IMPLS] + [("rustorb", "omniorbpy")]
    if runner.cxx:
        combos.append(("cxx", "rustorb"))
    failed = 0
    try:
        time.sleep(1)
        for rtc_impl, shell in combos:
            try:
                runner.run(rtc_impl, shell)
                why = ""
            except (Failed, subprocess.TimeoutExpired) as e:
                why = str(e)
            print("%-6s rtshell        RTCs=%-9s rtshell=%-9s %s" % (
                "FAIL" if why else "ok", rtc_impl, shell, why))
            sys.stdout.flush()
            failed += bool(why)
    finally:
        naming.terminate()
        naming.wait()
    print("\n%d failed" % failed)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
