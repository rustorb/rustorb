"""The C++ backend: ``rustorb-idl -bc++11``.

For ``Foo.idl`` it writes ``Foo.hh`` and ``Foo.cc`` (the suffixes can be
changed with ``-Wbh=`` and ``-Wbs=``), following the IDL to C++11 mapping:

- modules are namespaces, interfaces are classes (the stub of the
  interface), and ``IDL::traits<I>::ref_type`` is the reference type;
- structs, unions and exceptions are classes with accessor and modifier
  functions, enums are ``enum class``, sequences ``std::vector``, arrays
  ``std::array`` and strings ``std::string`` / ``std::wstring``;
- the skeleton of interface ``M::I`` is ``POA_M::I``, also reachable as
  ``CORBA::servant_traits<M::I>::base_type``.

The generated code uses the headers in ``cpp/include/rustorb`` (MIT OR
Apache-2.0): ``rustorb/corba.h`` for the mapping of the CORBA module, the
ORB and the POA, and ``rustorb/cdr.h`` for marshalling (the ``codec``
specialisations written here), invocations and dispatch.

Each type gets its TypeCode, ``_tc_<name>`` (built on first use by
``_rorb_tc_<name>()``, so that the order in which static objects are made
does not matter), and the C++ types that are only theirs (structs,
unions, enums, exceptions, interfaces) a ``rustorb::cdr::type_code``
specialisation, which ``any <<= value`` and ``any >>= value`` use.
``fixed<d, s>`` is ``IDL::Fixed<d, s>``.

A valuetype ``M::V`` is an abstract class with virtual accessors
(``IDL::traits<V>::ref_type`` is its reference type) and the concrete
class ``OBV_M::V`` that holds the state; a value box is a concrete class
with ``_value()``. The source registers each valuetype's TypeCode with
the core and, for those without operations, a factory of its ``OBV_``
class (or of the box). Custom valuetypes, ``supports``, valuetype
operations and abstract interfaces are not mapped yet.
"""

import os
import re

from . import frontend as fe

#: Must match rustorb::generated_code_version in rustorb/cdr.h.
GENERATED_CODE_VERSION = 3

HEADER = (
    "// Generated by rustorb-idl from %s. Do not edit.\n"
    "//\n"
    "// This file is not covered by the license of rustorb-idl.\n"
)

CXX_KEYWORDS = set(
    """
    alignas alignof and and_eq asm auto bitand bitor bool break case catch char
    char8_t char16_t char32_t class compl concept const consteval constexpr constinit
    const_cast continue co_await co_return co_yield decltype default delete do double
    dynamic_cast else enum explicit export extern false float for friend goto if inline
    int long mutable namespace new noexcept not not_eq nullptr operator or or_eq private
    protected public register reinterpret_cast requires return short signed sizeof static
    static_assert static_cast struct switch template this thread_local throw true try
    typedef typeid typename union unsigned using virtual void volatile wchar_t while xor
    xor_eq
    """.split()
)

BASIC = {
    "boolean": "bool",
    "octet": "uint8_t",
    "char": "char",
    "wchar": "wchar_t",
    "short": "int16_t",
    "ushort": "uint16_t",
    "long": "int32_t",
    "ulong": "uint32_t",
    "longlong": "int64_t",
    "ulonglong": "uint64_t",
    "float": "float",
    "double": "double",
}

INT_RANGES = {
    "short": (-(1 << 15), (1 << 15) - 1),
    "long": (-(1 << 31), (1 << 31) - 1),
    "longlong": (-(1 << 63), (1 << 63) - 1),
    "ushort": (0, (1 << 16) - 1),
    "ulong": (0, (1 << 32) - 1),
    "ulonglong": (0, (1 << 64) - 1),
    "octet": (0, 255),
}

TC_REF = "::IDL::traits<::CORBA::TypeCode>::ref_type"

UNSUPPORTED = {
    "Principal": "Principal",
    "longdouble": "long double",
}


def cxx_name(name):
    """An IDL identifier as a C++ identifier: C++ keywords get the prefix
    ``_cxx_``, as the IDL to C++11 mapping says."""
    if name in CXX_KEYWORDS:
        return "_cxx_" + name
    return name


def file_base(path):
    base = os.path.basename(path)
    if base.lower().endswith(".idl"):
        base = base[:-4]
    return base


class Writer(object):
    def __init__(self):
        self.lines = []
        self.level = 0

    def __call__(self, text=""):
        if text:
            self.lines.append("  " * self.level + text)
        else:
            self.lines.append("")

    def indent(self):
        self.level += 1

    def dedent(self):
        self.level -= 1

    def text(self):
        return "\n".join(self.lines) + "\n"


class Options(object):
    def __init__(self, header_suffix=".hh", source_suffix=".cc"):
        self.header_suffix = header_suffix
        self.source_suffix = source_suffix


_NONE = object()


class CxxBackend(object):
    # The language in errors (the Java backend shares check_value).
    LANGUAGE = "C++"

    def __init__(self, spec, options=None):
        self.spec = spec
        self.opt = options or Options()
        self.idl_name = os.path.basename(spec.path)
        self.base = file_base(spec.path)
        # What the header declares and the source defines.
        self.codecs = []  # (kind, node) for structs, unions, exceptions, enums
        self.typecodes = []  # definitions with a _tc_<name>
        self.interfaces = []  # full, non-local interface definitions
        self.values = []  # full valuetype and value box definitions
        self.ns = ()  # namespaces open in the header

    # -- names -----------------------------------------------------------

    def scoped(self, node):
        """The C++ name of a definition: ``::CosNaming::NamingContext``."""
        return "::" + "::".join(cxx_name(n) for n in fe.scope_path(node))

    def poa_scoped(self, node):
        """The skeleton class of an interface: ``::POA_M::I``."""
        mods = fe.enclosing_modules(node)
        if mods:
            return "::POA_%s::%s" % (
                mods[0],
                "::".join([cxx_name(m) for m in mods[1:]] + [cxx_name(node.name)]),
            )
        return "::POA_" + node.name

    def ops_name(self, node):
        """The member function of a skeleton that dispatches the operations
        of interface ``node`` itself."""
        return "_rorb_ops_" + "_".join(fe.scope_path(node))

    # -- types -----------------------------------------------------------

    def ctype(self, t, where=None):
        """The C++ type of a :class:`frontend.Type`."""
        k = t.kind
        if k in BASIC:
            return BASIC[k]
        if k in UNSUPPORTED:
            raise fe.GeneratorError(
                "%s is not supported by the C++ backend yet" % UNSUPPORTED[k], where
            )
        if k == "void":
            return "void"
        if k == "any":
            return "::CORBA::Any"
        if k == "TypeCode":
            return TC_REF
        if k == "Object":
            return "::IDL::traits<::CORBA::Object>::ref_type"
        if k == "string":
            return "::IDL::bounded_string<%d>" % t.bound if t.bound else "std::string"
        if k == "wstring":
            return "::IDL::bounded_wstring<%d>" % t.bound if t.bound else "std::wstring"
        if k == "sequence":
            inner = self.ctype(t.content, where)
            if t.bound:
                return "::IDL::bounded_vector<%s, %d>" % (inner, t.bound)
            return "std::vector<%s>" % inner
        if k == "array":
            return "std::array<%s, %d>" % (self.ctype(t.content, where), t.length)
        if k == "fixed":
            return "::IDL::Fixed<%d, %d>" % (t.digits, t.scale)
        if k == "named":
            n = t.node
            if fe.is_native(n):
                raise fe.GeneratorError("native %s cannot be used in C++" % n.name, where)
            if fe.is_interface(n):
                self.check_interface(n)
                return "::IDL::traits<%s>::ref_type" % self.scoped(n)
            if fe.is_valuetype(n):
                return "::IDL::traits<%s>::ref_type" % self.scoped(n)
            if fe.is_typedef(n) and self.is_objref(t):
                return "::IDL::traits<%s>::ref_type" % self.scoped(n)
            return self.scoped(n)
        raise fe.GeneratorError("no C++ type for %r" % t, where)

    def check_interface(self, n):
        if getattr(n, "is_abstract", False):
            raise fe.GeneratorError(
                "abstract interfaces are not supported by the C++ backend yet", n
            )

    def is_objref(self, t):
        r = t.resolved()
        return r.kind == "Object" or (r.kind == "named" and fe.is_interface(r.node))

    def is_value(self, t):
        r = t.resolved()
        return r.kind == "named" and fe.is_valuetype(r.node)

    def by_value(self, t):
        """Whether ``in`` arguments and accessors of the type are by value
        (basic types and enums)."""
        r = t.resolved()
        if r.kind in BASIC:
            return True
        return r.kind == "named" and fe.is_enum(r.node)

    def in_type(self, t, where=None):
        c = self.ctype(t, where)
        if (
            self.by_value(t)
            or self.is_objref(t)
            or self.is_value(t)
            or t.resolved().kind == "TypeCode"
        ):
            return c
        return "const %s&" % c

    # -- values ----------------------------------------------------------

    def literal(self, value, t):
        """A C++ expression for a constant of type ``t``."""
        r = t.resolved()
        k = r.kind
        if k == "named" and fe.is_enum(r.node):
            return self.enumerator_ref(value)
        if k == "boolean":
            return "true" if value else "false"
        if k in ("float", "double"):
            v = float(value)
            if v != v:
                expr = "std::numeric_limits<%s>::quiet_NaN()" % BASIC[k]
            elif v in (float("inf"), float("-inf")):
                expr = "%sstd::numeric_limits<%s>::infinity()" % ("-" if v < 0 else "", BASIC[k])
            else:
                expr = repr(v)
                if "e" not in expr and "." not in expr and "n" not in expr:
                    expr += ".0"
                if k == "float":
                    expr += "f"
            return expr
        if k in ("char", "wchar"):
            c = value if isinstance(value, str) else chr(value)
            return ("L" if k == "wchar" else "") + "'" + _escape_char(c, k == "wchar") + "'"
        if k == "fixed":
            return '%s("%s")' % (self.ctype(r), fixed_text(value, r.digits, r.scale))
        if k in ("string", "wstring"):
            text = '"%s"' % _escape_string(str(value), k == "wstring")
            return ("L" + text) if k == "wstring" else text
        if k in INT_RANGES:
            v = int(value)
            lo, hi = INT_RANGES[k]
            if v < lo or v > hi:
                raise fe.GeneratorError("constant %d out of range for %s" % (v, k))
            if k == "longlong":
                if v == lo:
                    return "(-9223372036854775807LL - 1)"
                return "%dLL" % v
            if k == "ulonglong":
                return "%dULL" % v
            if k == "ulong":
                return "%dU" % v
            if k == "long" and v == lo:
                return "(-2147483647 - 1)"
            if k in ("short", "ushort", "octet"):
                return "static_cast<%s>(%d)" % (BASIC[k], v)
            return "%d" % v
        raise fe.GeneratorError("no C++ literal for a constant of type %r" % r)

    def enumerator_ref(self, item):
        enum = item.parent
        return self.scoped(enum) + "::" + cxx_name(item.name)

    # -- the header ------------------------------------------------------

    def open_ns(self, w, mods):
        """Opens the namespaces ``mods`` in the header, closing others."""
        mods = tuple(cxx_name(m) for m in mods)
        common = 0
        while common < min(len(mods), len(self.ns)) and mods[common] == self.ns[common]:
            common += 1
        for m in reversed(self.ns[common:]):
            w.dedent()
            w("}  // namespace %s" % m)
            w()
        for m in mods[common:]:
            w("namespace %s {" % m)
            w.indent()
            w()
        self.ns = mods

    def generate_header(self):
        w = Writer()
        guard = "RUSTORB_IDL_%s_HH" % re.sub(r"[^0-9A-Za-z]", "_", self.base).upper()
        w(HEADER % self.idl_name)
        w("#ifndef %s" % guard)
        w("#define %s" % guard)
        w()
        w("#include <rustorb/cdr.h>")
        w()
        w("#include <array>")
        w("#include <cstdint>")
        w("#include <limits>")
        w("#include <string>")
        w("#include <vector>")
        w()
        included = self.spec.included_files()
        for f in included:
            w('#include "%s%s"' % (file_base(f), self.opt.header_suffix))
        if included:
            w()
        w(
            "static_assert(::rustorb::generated_code_version == %d,"
            % GENERATED_CODE_VERSION
        )
        w('              "%s was generated for another version of rustorb");' % self.idl_name)
        w()
        for it in fe.definitions(self.spec):
            n = it.node
            if fe.is_module(n) or fe.is_operation(n) or fe.is_attribute(n):
                continue
            self.open_ns(w, fe.enclosing_modules(n))
            self.definition(w, n, in_class=False)
        self.open_ns(w, ())
        self.obv_classes(w)
        self.skeletons(w)
        self.codec_declarations(w)
        w("#endif")
        return w.text()

    def definition(self, w, node, in_class):
        if fe.is_const(node):
            self.const(w, node, in_class)
        elif fe.is_enum(node):
            self.enum(w, node)
            self.typecode_declaration(w, node, in_class)
        elif fe.is_typedef(node):
            t = fe.type_of(node.type, node)
            w("using %s = %s;" % (cxx_name(node.name), self.ctype(t, node)))
            w()
            self.typecode_declaration(w, node, in_class)
        elif fe.is_exception(node):
            self.struct(w, node, exception=True)
            self.typecode_declaration(w, node, in_class)
        elif fe.is_struct(node):
            if fe.is_forward(node):
                w("class %s;" % cxx_name(node.name))
                w()
            else:
                self.struct(w, node)
                self.typecode_declaration(w, node, in_class)
        elif fe.is_union(node):
            if fe.is_forward(node):
                w("class %s;" % cxx_name(node.name))
                w()
            else:
                self.union(w, node)
                self.typecode_declaration(w, node, in_class)
        elif fe.is_interface(node):
            self.check_interface(node)
            if fe.is_forward(node):
                w("class %s;" % cxx_name(node.name))
                w()
            else:
                self.interface(w, node)
                self.typecode_declaration(w, node, in_class)
        elif fe.is_native(node):
            w("// native %s is not mapped" % node.name)
            w()
        elif fe.is_valuetype(node):
            if fe.is_forward(node):
                w("class %s;" % cxx_name(node.name))
                w()
            elif node.is_boxed:
                self.value_box(w, node)
                self.typecode_declaration(w, node, in_class)
            else:
                self.valuetype(w, node)
                self.typecode_declaration(w, node, in_class)
        else:
            raise fe.GeneratorError(
                "%s definitions are not supported yet" % fe.kind_name(node), node
            )

    def nested(self, w, scope):
        """The types and constants defined inside a struct, union,
        exception or interface."""
        for d in fe.members_of(scope):
            if fe.is_operation(d) or fe.is_attribute(d):
                continue
            if (
                fe.is_struct(d)
                or fe.is_union(d)
                or fe.is_exception(d)
                or fe.is_enum(d)
                or fe.is_typedef(d)
                or fe.is_const(d)
                or fe.is_native(d)
            ):
                self.definition(w, d, in_class=True)

    def const(self, w, node, in_class):
        t = fe.type_of(node.type, node)
        r = t.resolved()
        value = self.literal(node.value, t)
        ctype = self.ctype(t, node)
        if r.kind in ("string", "wstring", "fixed"):
            decl = "inline const %s %s = %s;" % (ctype, cxx_name(node.name), value)
        else:
            decl = "inline constexpr %s %s = %s;" % (ctype, cxx_name(node.name), value)
        w(("static " + decl) if in_class else decl)
        w()

    def enum(self, w, node):
        names = [cxx_name(v.name) for v in node.values]
        w("enum class %s : uint32_t { %s };" % (cxx_name(node.name), ", ".join(names)))
        w()
        self.codecs.append(("enum", node))

    # TypeCodes

    def typecode_declaration(self, w, node, in_class):
        """``_tc_<name>`` and the function that makes it, after the
        definition of ``node``."""
        if in_class:
            w("static %s _rorb_tc_%s();" % (TC_REF, node.name))
            w("static const %s _tc_%s;" % (TC_REF, node.name))
        else:
            w("%s _rorb_tc_%s();" % (TC_REF, node.name))
            w("extern const %s _tc_%s;" % (TC_REF, node.name))
        w()
        self.typecodes.append(node)

    def tc_scope(self, node):
        """``M::I::`` for the definitions of ``node``'s TypeCode (no
        leading ``::``)."""
        path = [cxx_name(n) for n in fe.scope_path(node)][:-1]
        return "".join(p + "::" for p in path)

    def tc_function(self, node):
        return "::" + self.tc_scope(node) + "_rorb_tc_" + node.name

    def full(self, node):
        """The full definition of a forward-declared struct, union or
        valuetype."""
        if fe.is_valuetype(node) and fe.is_forward(node):
            full = fe.full_definition(node)
            if full is None:
                raise fe.GeneratorError("%s is declared but not defined" % node.name, node)
            return full
        if (fe.is_struct(node) or fe.is_union(node)) and fe.is_forward(node):
            for d in node.parent.definitions:
                if type(d) is type(node) and d.name == node.name and not fe.is_forward(d):
                    return d
            raise fe.GeneratorError("%s is declared but not defined" % node.name, node)
        return node

    def member_types(self, node):
        if fe.is_typedef(node):
            return [fe.type_of(node.type, node)]
        if fe.is_struct(node) or fe.is_exception(node):
            return [t for _, t in self.members(node)]
        if fe.is_union(node):
            return [t for _, _, t in self.union_cases(node)[1]]
        if fe.is_valuetype(node):
            if node.is_boxed:
                return [fe.type_of(node.boxed_type, node)]
            base = fe.concrete_base(node)
            own = [t for _, t, _ in self.state_members(node)]
            return own + ([fe.Type("named", node=base)] if base is not None else [])
        return []

    def reaches(self, t, open_, seen):
        """Whether type ``t`` contains one of the structs or unions in
        ``open_`` (whose TypeCodes are being made)."""
        if t.kind in ("sequence", "array"):
            return self.reaches(t.content, open_, seen)
        if t.kind != "named":
            return False
        n = self.full(t.node)
        if any(n is o for o in open_):
            return True
        if any(n is x for x in seen):
            return False
        seen.append(n)
        return any(self.reaches(m, open_, seen) for m in self.member_types(n))

    def tc_expr(self, t, where, open_=()):
        """A C++ expression for the TypeCode of ``t``. ``open_`` are the
        structs and unions whose TypeCodes contain this one: references to
        them are recursive, and types that contain them are made in
        place rather than by their ``_rorb_tc_`` function."""
        k = t.kind
        if k in BASIC:
            return "::rustorb::cdr::type_code<%s>::get()" % BASIC[k]
        if k == "any":
            return "::rustorb::cdr::type_code<::CORBA::Any>::get()"
        if k == "TypeCode":
            return "::rustorb::cdr::type_code<::CORBA::TypeCode>::get()"
        if k == "Object":
            return "::rustorb::cdr::type_code<::CORBA::Object>::get()"
        if k in ("string", "wstring"):
            return "::rustorb::detail::tc_string(%s, %d)" % (
                "true" if k == "wstring" else "false",
                t.bound,
            )
        if k == "fixed":
            return "::rustorb::cdr::type_code<%s>::get()" % self.ctype(t, where)
        if k == "sequence":
            return "::rustorb::detail::tc_sequence(%s, %d)" % (
                self.tc_expr(t.content, where, open_),
                t.bound,
            )
        if k == "array":
            return "::rustorb::detail::tc_array(%s, %d)" % (
                self.tc_expr(t.content, where, open_),
                t.length,
            )
        if k == "named":
            n = self.full(t.node)
            if any(n is o for o in open_):
                return '::rustorb::detail::tc_recursive("%s")' % fe.repository_id(n)
            if open_ and self.reaches(t, open_, []):
                return self.tc_build(n, open_)
            if fe.is_native(n):
                raise fe.GeneratorError("native %s cannot be used in C++" % n.name, where)
            return self.tc_function(n) + "()"
        self.ctype(t, where)  # raises for the unsupported ones
        raise fe.GeneratorError("no TypeCode for %r" % t, where)

    def tc_build(self, node, open_):
        """A C++ expression that makes the TypeCode of ``node``."""
        rid = '"%s"' % fe.repository_id(node)
        name = '"%s"' % node.name
        if fe.is_typedef(node):
            content = self.tc_expr(fe.type_of(node.type, node), node, open_)
            return "::rustorb::detail::tc_alias(::CORBA::TCKind::tk_alias, %s, %s, %s)" % (
                rid,
                name,
                content,
            )
        if fe.is_enum(node):
            return "::rustorb::detail::tc_enum(%s, %s, {%s})" % (
                rid,
                name,
                ", ".join('"%s"' % v.name for v in node.values),
            )
        if fe.is_interface(node):
            kind = "tk_local_interface" if getattr(node, "is_local", False) else "tk_objref"
            return "::rustorb::detail::tc_interface(::CORBA::TCKind::%s, %s, %s)" % (
                kind,
                rid,
                name,
            )
        inner = tuple(open_) + (node,)
        if fe.is_valuetype(node) and node.is_boxed:
            return "::rustorb::detail::tc_alias(::CORBA::TCKind::tk_value_box, %s, %s, %s)" % (
                rid,
                name,
                self.tc_expr(fe.type_of(node.boxed_type, node), node, inner),
            )
        if fe.is_valuetype(node):
            base = fe.concrete_base(node)
            members = ", ".join(
                '{"%s", %s, %s}'
                % (
                    m,
                    self.tc_expr(t, node, inner),
                    "::CORBA::PUBLIC_MEMBER" if public else "::CORBA::PRIVATE_MEMBER",
                )
                for m, t, public in self.state_members(node)
            )
            return "::rustorb::detail::tc_value(%s, %s, ::CORBA::%s, %s, {%s})" % (
                rid,
                name,
                self.value_modifier(node),
                self.tc_expr(fe.Type("named", node=base), node, inner)
                if base is not None
                else "nullptr",
                members,
            )
        if fe.is_struct(node) or fe.is_exception(node):
            kind = "tk_except" if fe.is_exception(node) else "tk_struct"
            members = ", ".join(
                '{"%s", %s}' % (m, self.tc_expr(t, node, inner)) for m, t in self.members(node)
            )
            return "::rustorb::detail::tc_struct(::CORBA::TCKind::%s, %s, %s, {%s})" % (
                kind,
                rid,
                name,
                members,
            )
        if fe.is_union(node):
            disc, cases, default_index = self.union_cases(node)
            rdisc = disc.resolved()
            entries = []
            default_entry = -1
            for i, (labels, m, t) in enumerate(cases):
                expr = self.tc_expr(t, node, inner)
                for label in labels:
                    entries.append(
                        '{%s, "%s", %s}' % (self.label_bits(label, rdisc), m, expr)
                    )
                if i == default_index:
                    default_entry = len(entries)
                    entries.append('{0, "%s", %s}' % (m, expr))
            return "::rustorb::detail::tc_union(%s, %s, %s, {%s}, %d)" % (
                rid,
                name,
                self.tc_expr(disc, node, inner),
                ", ".join(entries),
                default_entry,
            )
        raise fe.GeneratorError("no TypeCode for %s" % node.name, node)

    def label_bits(self, label, disc):
        """A union label as rorb_tc_union takes it."""
        if hasattr(label, "name") and hasattr(label, "parent"):
            v = [x.name for x in disc.node.values].index(label.name)
        elif disc.kind == "boolean":
            v = 1 if label else 0
        elif disc.kind in ("char", "wchar"):
            v = ord(label) if isinstance(label, str) else int(label)
        else:
            v = int(label)
        return "%dULL" % (v & ((1 << 64) - 1))

    def typecode_definitions(self, w):
        for node in self.typecodes:
            scope = self.tc_scope(node)
            w("%s %s_rorb_tc_%s() {" % (TC_REF, scope, node.name))
            w("  static const %s _tc = %s;" % (TC_REF, self.tc_build(node, ())))
            w("  return _tc;")
            w("}")
            w()
            w("const %s %s_tc_%s = %s_rorb_tc_%s();" % (TC_REF, scope, node.name, scope, node.name))
            w()

    # structs and exceptions

    def members(self, node):
        if getattr(node, "base", None) is not None:
            raise fe.GeneratorError("struct inheritance is not supported", node)
        return [(m.name, fe.type_of(m.type, m)) for m in node.members]

    def accessors(self, w, name, t, where, storage, before=""):
        """Accessor and modifier functions of a member; ``before`` is code
        run first by each of them (unions check or set the
        discriminator)."""
        c = self.ctype(t, where)
        n = cxx_name(name)
        if self.by_value(t):
            w("void %s(%s _v) { %s%s = _v; }" % (n, c, before, storage))
            w("%s %s() const { return %s; }" % (c, n, storage))
        else:
            w("void %s(const %s& _v) { %s%s = _v; }" % (n, c, before, storage))
            w("void %s(%s&& _v) { %s%s = std::move(_v); }" % (n, c, before, storage))
            w("const %s& %s() const { return %s; }" % (c, n, storage))
        w("%s& %s() { return %s; }" % (c, n, storage))

    def struct(self, w, node, exception=False):
        name = cxx_name(node.name)
        members = self.members(node)
        if exception:
            w("class %s : public ::CORBA::UserException {" % name)
        else:
            w("class %s {" % name)
        w(" public:")
        w.indent()
        self.nested(w, node)
        if exception:
            w('static constexpr const char* _rorb_repository_id = "%s";' % fe.repository_id(node))
            w()
        w("%s() = default;" % name)
        if members:
            params = ", ".join("%s %s" % (self.in_type(t, node), cxx_name(m)) for m, t in members)
            inits = ", ".join("_m_%s(%s)" % (m, cxx_name(m)) for m, _ in members)
            w("explicit %s(%s) : %s {}" % (name, params, inits))
        w()
        for m, t in members:
            self.accessors(w, m, t, node, "_m_" + m)
            w()
        if exception:
            w('const char* _name() const override { return "%s"; }' % node.name)
            w("const char* _rep_id() const override { return _rorb_repository_id; }")
            w("[[noreturn]] void _raise() const override { throw *this; }")
            w()
        w("friend bool operator==(const %s& a, const %s& b) {" % (name, name))
        if members:
            w("  return %s;" % " &&\n         ".join("a._m_%s == b._m_%s" % (m, m) for m, _ in members))
        else:
            w("  (void)a;")
            w("  (void)b;")
            w("  return true;")
        w("}")
        w(
            "friend bool operator!=(const %s& a, const %s& b) { return !(a == b); }"
            % (name, name)
        )
        w.dedent()
        w()
        w(" private:")
        w.indent()
        for m, t in members:
            w("%s _m_%s {};" % (self.ctype(t, node), m))
        w.dedent()
        w("};")
        w()
        self.codecs.append(("exception" if exception else "struct", node))

    # unions

    def union_cases(self, node):
        """``(disc Type, cases, default member index)``: cases are
        ``(labels, member name, Type)`` per member, labels without the
        ``default`` one."""
        disc = fe.type_of(node.discriminator_type, node)
        cases = []
        default_index = -1
        for i, m in enumerate(node.members):
            cases.append((list(m.labels), m.name, fe.type_of(m.type, m)))
            if m.is_default:
                default_index = i
        return disc, cases, default_index

    def default_discriminator(self, disc, labels):
        """The first value of the discriminator type, in order, that no
        label uses (for an integer type, counting up from its smallest
        value), or _NONE."""
        k = disc.kind
        used = set()
        for label in labels:
            if hasattr(label, "name") and hasattr(label, "parent"):
                used.add(label.name)
            else:
                used.add(label)
        if k in INT_RANGES:
            lo, hi = INT_RANGES[k]
            v = lo
            while v in used and v <= hi:
                v += 1
            return v if v <= hi else _NONE
        if k == "boolean":
            for v in (False, True):
                if v not in used:
                    return v
            return _NONE
        if k in ("char", "wchar"):
            for c in range(0, 256 if k == "char" else 0x10000):
                if chr(c) not in used:
                    return chr(c)
            return _NONE
        if k == "named" and fe.is_enum(disc.node):
            for v in disc.node.values:
                if v.name not in used:
                    return v
            return _NONE
        raise fe.GeneratorError("unsupported union discriminator type %r" % disc)

    def union(self, w, node):
        name = cxx_name(node.name)
        disc, cases, default_index = self.union_cases(node)
        rdisc = disc.resolved()
        dt = self.ctype(disc, node)
        labels = [l for ls, _, _ in cases for l in ls]
        implicit = self.default_discriminator(rdisc, labels)
        lit = lambda v: self.literal(v, disc)  # noqa: E731

        if default_index >= 0:
            if implicit is _NONE:
                raise fe.GeneratorError("the labels of union %s leave no default" % name, node)
            init_d = lit(implicit)
        elif implicit is not _NONE:
            init_d = lit(implicit)
        else:
            init_d = lit(cases[0][0][0])

        w("class %s {" % name)
        w(" public:")
        w.indent()
        self.nested(w, node)
        w("%s() : _m__d(%s) {}" % (name, init_d))
        w()
        w("%s _d() const { return _m__d; }" % dt)
        w("void _d(%s d) {" % dt)
        w("  if (_rorb_member(d) != _rorb_member(_m__d))")
        w("    throw ::CORBA::BAD_PARAM(0, ::CORBA::CompletionStatus::COMPLETED_NO);")
        w("  _m__d = d;")
        w("}")
        if default_index < 0 and implicit is not _NONE:
            w("void _default() { _rorb_reset(%s); }" % lit(implicit))
        w()
        for i, (ls, m, t) in enumerate(cases):
            first = lit(ls[0]) if ls else lit(implicit)
            c = self.ctype(t, node)
            n = cxx_name(m)
            storage = "_m_" + m
            # modifiers: set the member and its (first) label
            if self.by_value(t):
                w("void %s(%s _v) { _rorb_reset(%s); %s = _v; }" % (n, c, first, storage))
                w(
                    "void %s(%s _v, %s d) { _rorb_set(%d, d); %s = _v; }"
                    % (n, c, dt, i, storage)
                )
                w("%s %s() const { _rorb_check(%d); return %s; }" % (c, n, i, storage))
            else:
                w(
                    "void %s(const %s& _v) { _rorb_reset(%s); %s = _v; }"
                    % (n, c, first, storage)
                )
                w(
                    "void %s(%s&& _v) { _rorb_reset(%s); %s = std::move(_v); }"
                    % (n, c, first, storage)
                )
                w(
                    "void %s(const %s& _v, %s d) { _rorb_set(%d, d); %s = _v; }"
                    % (n, c, dt, i, storage)
                )
                w("const %s& %s() const { _rorb_check(%d); return %s; }" % (c, n, i, storage))
            w("%s& %s() { _rorb_check(%d); return %s; }" % (c, n, i, storage))
            w()
        # the member of a discriminator value
        w("// The member a discriminator value selects (-1 for none).")
        w("static int _rorb_member(%s d) {" % dt)
        w.indent()
        if rdisc.kind == "boolean":
            # switch on bool warns; compare instead
            for i, (ls, _, _) in enumerate(cases):
                for l in ls:
                    w("if (d == %s) return %d;" % (lit(l), i))
            w("(void)d;")
            w("return %d;" % default_index)
        else:
            w("switch (d) {")
            w.indent()
            for i, (ls, _, _) in enumerate(cases):
                for l in ls:
                    w("case %s:" % lit(l))
                if ls:
                    w("  return %d;" % i)
            w("default:")
            w("  return %d;" % default_index)
            w.dedent()
            w("}")
        w.dedent()
        w("}")
        w("// Clears the members and sets the discriminator.")
        w("void _rorb_reset(%s d) {" % dt)
        for _, m, t in cases:
            w("  _m_%s = %s{};" % (m, self.ctype(t, node)))
        w("  _m__d = d;")
        w("}")
        w()
        w("friend bool operator==(const %s& a, const %s& b) {" % (name, name))
        w("  if (a._m__d != b._m__d) return false;")
        w("  switch (_rorb_member(a._m__d)) {")
        for i, (_, m, _) in enumerate(cases):
            w("    case %d: return a._m_%s == b._m_%s;" % (i, m, m))
        w("    default: return true;")
        w("  }")
        w("}")
        w(
            "friend bool operator!=(const %s& a, const %s& b) { return !(a == b); }"
            % (name, name)
        )
        w.dedent()
        w()
        w(" private:")
        w.indent()
        w("void _rorb_check(int i) const {")
        w("  if (_rorb_member(_m__d) != i)")
        w("    throw ::CORBA::BAD_PARAM(0, ::CORBA::CompletionStatus::COMPLETED_NO);")
        w("}")
        w("void _rorb_set(int i, %s d) {" % dt)
        w("  if (_rorb_member(d) != i)")
        w("    throw ::CORBA::BAD_PARAM(0, ::CORBA::CompletionStatus::COMPLETED_NO);")
        w("  _rorb_reset(d);")
        w("}")
        w()
        w("%s _m__d;" % dt)
        for _, m, t in cases:
            w("%s _m_%s {};" % (self.ctype(t, node), m))
        w.dedent()
        w("};")
        w()
        self.codecs.append(("union", node))

    # valuetypes

    def value_modifier(self, node):
        if node.is_abstract:
            return "VM_ABSTRACT"
        if node.is_truncatable:
            return "VM_TRUNCATABLE"
        return "VM_NONE"

    def state_members(self, node):
        """``[(name, Type, public)]`` of the valuetype's own state members."""
        return [(m.name, fe.type_of(m.type, m), m.is_public) for m in node.state_members]

    def all_state_members(self, node):
        """The state members of the valuetype and its concrete bases, those
        of the bases first."""
        base = fe.concrete_base(node)
        inherited = self.all_state_members(base) if base is not None else []
        return inherited + self.state_members(node)

    def check_value(self, node):
        backend = "the %s backend" % self.LANGUAGE
        if node.is_custom:
            raise fe.GeneratorError("custom valuetypes are not supported by %s yet" % backend, node)
        if node.supports:
            raise fe.GeneratorError(
                "valuetypes that support interfaces are not supported by %s yet" % backend, node
            )
        if fe.has_behaviour(node):
            raise fe.GeneratorError(
                "valuetype operations, attributes and initializers are not supported by %s yet"
                % backend,
                node,
            )

    def value_accessors(self, w, name, t, where, prefix, suffix):
        """The accessors and modifiers of a state member, as declarations
        ``prefix ... suffix``."""
        c = self.ctype(t, where)
        n = cxx_name(name)
        if self.by_value(t):
            w("%s%s %s() const%s" % (prefix, c, n, suffix))
            w("%svoid %s(%s _v)%s" % (prefix, n, c, suffix))
        else:
            w("%sconst %s& %s() const%s" % (prefix, c, n, suffix))
            w("%svoid %s(const %s& _v)%s" % (prefix, n, c, suffix))
            w("%svoid %s(%s&& _v)%s" % (prefix, n, c, suffix))
        w("%s%s& %s()%s" % (prefix, c, n, suffix))

    def valuetype(self, w, node):
        self.check_value(node)
        name = cxx_name(node.name)
        bases = fe.value_bases(node)
        if bases:
            base_list = ", ".join("public virtual %s" % self.scoped(self.full(b)) for b in bases)
        else:
            base_list = "public virtual ::CORBA::ValueBase"
        w("class %s : %s {" % (name, base_list))
        w(" public:")
        w.indent()
        w('static constexpr const char* _rorb_repository_id = "%s";' % fe.repository_id(node))
        w()
        self.nested(w, node)
        members = self.state_members(node)
        for m, t, public in members:
            if public:
                self.value_accessors(w, m, t, node, "virtual ", " = 0;")
        if not node.is_abstract:
            w()
            w("const std::vector<const char*>& _rorb_ids() const override;")
            w("void _rorb_write_state(rorb_out* out) const override;")
            w("void _rorb_read_state(rorb_in* in) override;")
        w.dedent()
        w()
        w(" protected:")
        w.indent()
        w("%s() = default;" % name)
        for m, t, public in members:
            if not public:
                self.value_accessors(w, m, t, node, "virtual ", " = 0;")
        w.dedent()
        w("};")
        w()
        self.values.append(node)

    def value_box(self, w, node):
        name = cxx_name(node.name)
        t = fe.type_of(node.boxed_type, node)
        c = self.ctype(t, node)
        w("class %s : public ::CORBA::ValueBase {" % name)
        w(" public:")
        w.indent()
        w('static constexpr const char* _rorb_repository_id = "%s";' % fe.repository_id(node))
        w()
        w("%s() = default;" % name)
        w("explicit %s(%s _v) : _m_value(std::move(_v)) {}" % (name, c))
        w()
        self.accessors(w, "_value", t, node, "_m_value")
        w()
        w("::IDL::traits<::CORBA::ValueBase>::ref_type _copy_value() const override;")
        w("const std::vector<const char*>& _rorb_ids() const override;")
        w("void _rorb_write_state(rorb_out* out) const override;")
        w("void _rorb_read_state(rorb_in* in) override;")
        w.dedent()
        w()
        w(" private:")
        w("  %s _m_value {};" % c)
        w("};")
        w()
        self.values.append(node)

    def obv_scoped(self, node):
        """The concrete class of a valuetype: ``::OBV_M::V``."""
        mods = fe.enclosing_modules(node)
        if mods:
            return "::OBV_%s::%s" % (
                mods[0],
                "::".join([cxx_name(m) for m in mods[1:]] + [cxx_name(node.name)]),
            )
        return "::OBV_" + node.name

    def has_obv(self, node):
        return not node.is_boxed and not node.is_abstract

    def obv_classes(self, w):
        for node in self.values:
            if not self.has_obv(node):
                continue
            mods = fe.enclosing_modules(node)
            if mods:
                w("namespace OBV_%s {" % mods[0])
                for m in mods[1:]:
                    w("namespace %s {" % cxx_name(m))
                w()
                cls = cxx_name(node.name)
            else:
                cls = "OBV_" + node.name
            members = self.all_state_members(node)
            w("class %s : public virtual %s {" % (cls, self.scoped(node)))
            w(" public:")
            w.indent()
            w("%s() = default;" % cls)
            if members:
                params = ", ".join(
                    "%s %s" % (self.in_type(t, node), cxx_name(m)) for m, t, _ in members
                )
                inits = ", ".join("_m_%s(%s)" % (m, cxx_name(m)) for m, _, _ in members)
                w(
                    "%s%s(%s) : %s {}"
                    % ("explicit " if len(members) == 1 else "", cls, params, inits)
                )
            w()
            for m, t, public in members:
                if public:
                    self.obv_accessors(w, m, t, node)
            w(
                "::IDL::traits<::CORBA::ValueBase>::ref_type _copy_value() const override {"
            )
            w(
                "  return ::IDL::traits<::CORBA::ValueBase>::ref_type(std::make_shared<%s>(*this));"
                % cls
            )
            w("}")
            w.dedent()
            w()
            w(" protected:")
            w.indent()
            for m, t, public in members:
                if not public:
                    self.obv_accessors(w, m, t, node)
            w.dedent()
            w()
            w(" private:")
            w.indent()
            for m, t, _ in members:
                w("%s _m_%s {};" % (self.ctype(t, node), m))
            w.dedent()
            w("};")
            w()
            if mods:
                for m in reversed(mods[1:]):
                    w("}  // namespace %s" % cxx_name(m))
                w("}  // namespace OBV_%s" % mods[0])
                w()

    def obv_accessors(self, w, name, t, where):
        c = self.ctype(t, where)
        n = cxx_name(name)
        storage = "_m_" + name
        if self.by_value(t):
            w("%s %s() const override { return %s; }" % (c, n, storage))
            w("void %s(%s _v) override { %s = _v; }" % (n, c, storage))
        else:
            w("const %s& %s() const override { return %s; }" % (c, n, storage))
            w("void %s(const %s& _v) override { %s = _v; }" % (n, c, storage))
            w("void %s(%s&& _v) override { %s = std::move(_v); }" % (n, c, storage))
        w("%s& %s() override { return %s; }" % (c, n, storage))

    def sent_ids(self, node):
        """The repository ids a value of ``node`` is sent with: its own,
        then those of the bases it is truncatable to."""
        ids = [fe.repository_id(node)]
        n = node
        while not n.is_boxed and n.is_truncatable:
            base = fe.concrete_base(n)
            if base is None:
                break
            n = self.full(base)
            ids.append(fe.repository_id(n))
        return ids

    def value_source(self, w, node):
        cls = self.scoped(node)
        if node.is_boxed:
            t = fe.type_of(node.boxed_type, node)
            w(
                "::IDL::traits<::CORBA::ValueBase>::ref_type %s::_copy_value() const {" % cls[2:]
            )
            w(
                "  return ::IDL::traits<::CORBA::ValueBase>::ref_type(std::make_shared<%s>(*this));"
                % cls
            )
            w("}")
            w()
        elif node.is_abstract:
            return
        w("const std::vector<const char*>& %s::_rorb_ids() const {" % cls[2:])
        w(
            "  static const std::vector<const char*> _ids{%s};"
            % ", ".join('"%s"' % i for i in self.sent_ids(node))
        )
        w("  return _ids;")
        w("}")
        w()
        if node.is_boxed:
            w("void %s::_rorb_write_state(rorb_out* out) const {" % cls[2:])
            w("  %s::write(out, _m_value);" % self.codec_of(t, node))
            w("}")
            w()
            w("void %s::_rorb_read_state(rorb_in* in) {" % cls[2:])
            w("  %s::read(in, _m_value);" % self.codec_of(t, node))
            w("}")
            w()
            return
        base = fe.concrete_base(node)
        members = self.state_members(node)
        w("void %s::_rorb_write_state(rorb_out* out) const {" % cls[2:])
        if base is not None:
            w("  %s::_rorb_write_state(out);" % self.scoped(self.full(base)))
        for m, t, _ in members:
            w("  %s::write(out, %s());" % (self.codec_of(t, node), cxx_name(m)))
        if base is None and not members:
            w("  (void)out;")
        w("}")
        w()
        w("void %s::_rorb_read_state(rorb_in* in) {" % cls[2:])
        if base is not None:
            w("  %s::_rorb_read_state(in);" % self.scoped(self.full(base)))
        for m, t, _ in members:
            w("  %s::read(in, %s());" % (self.codec_of(t, node), cxx_name(m)))
        if base is None and not members:
            w("  (void)in;")
        w("}")
        w()

    def value_registrations(self, w):
        if not self.values:
            return
        w("namespace {")
        for i, node in enumerate(self.values):
            if node.is_boxed:
                factory = "std::make_shared<::rustorb::detail::DefaultValueFactory<%s>>()" % (
                    self.scoped(node)
                )
            elif self.has_obv(node):
                factory = "std::make_shared<::rustorb::detail::DefaultValueFactory<%s>>()" % (
                    self.obv_scoped(node)
                )
            else:
                factory = None
            w(
                'const ::rustorb::detail::ValueRegistration _rorb_value_%d("%s", %s, %s());'
                % (
                    i,
                    fe.repository_id(node),
                    "::CORBA::ValueFactory(%s)" % factory if factory else "nullptr",
                    self.tc_function(node),
                )
            )
        w("}  // namespace")
        w()

    # interfaces

    def bases(self, node):
        return [b if fe.is_interface(b) else b.obj for b in node.inheritances]

    def ancestors(self, node):
        """Every base interface, transitively, each once, nearest first."""
        out = []
        todo = list(self.bases(node))
        while todo:
            b = todo.pop(0)
            if fe.is_forward(b):
                full = fe.full_definition(b)
                b = full if full is not None else b
            if any(a is b for a in out):
                continue
            out.append(b)
            todo.extend(self.bases(b))
        return out

    def operations(self, node):
        """``[(op name, method name, return Type, [(param, Type, direction)],
        raised exceptions, oneway)]`` for the operations and attribute
        accessors of the interface itself."""
        ops = []
        for d in fe.members_of(node):
            if fe.is_operation(d):
                ret = fe.type_of(d.returns, d)
                params = [
                    (a.name, fe.type_of(a.type, a), a.direction) for a in d.arguments
                ]
                excs = fe.raised_exceptions(d)
                ops.append((d.name, d.name, ret, params, excs, bool(d.oneway), d))
            elif fe.is_attribute(d):
                t = fe.type_of(d.type, d)
                get_ex = _resolve_exceptions(d, d.getraises)
                ops.append(("_get_" + d.name, d.name, t, [], get_ex, False, d))
                if not d.readonly:
                    set_ex = _resolve_exceptions(d, d.setraises)
                    ops.append(
                        (
                            "_set_" + d.name,
                            d.name,
                            fe.Type("void"),
                            [("value", t, "in")],
                            set_ex,
                            False,
                            d,
                        )
                    )
        return ops

    def signature(self, method, ret, params, where, qualifier=""):
        args = []
        for p, t, direction in params:
            if direction == "in":
                args.append("%s %s" % (self.in_type(t, where), cxx_name(p)))
            else:
                args.append("%s& %s" % (self.ctype(t, where), cxx_name(p)))
        return "%s %s%s(%s)" % (
            self.ctype(ret, where),
            qualifier,
            cxx_name(method),
            ", ".join(args),
        )

    def interface(self, w, node):
        name = cxx_name(node.name)
        bases = self.bases(node)
        local = bool(getattr(node, "is_local", False))
        if bases:
            base_list = ", ".join("public virtual %s" % self.scoped(b) for b in bases)
        else:
            base_list = "public virtual ::CORBA::%s" % ("LocalObject" if local else "Object")
        w("class %s : %s {" % (name, base_list))
        w(" public:")
        w.indent()
        if not local:
            w('static constexpr const char* _rorb_repository_id = "%s";' % fe.repository_id(node))
            w(
                "%s(::rustorb::detail::adopt_t, rorb_object* _h) noexcept"
                " : ::CORBA::Object(::rustorb::detail::adopt, _h) {}" % name
            )
            w()
        self.nested(w, node)
        for _, method, ret, params, _, _, d in self.operations(node):
            sig = self.signature(method, ret, params, d)
            w(("virtual %s = 0;" if local else "virtual %s;") % sig)
        w.dedent()
        w()
        w(" protected:")
        w("  %s() = default;" % name)
        w("};")
        w()
        if not local:
            self.interfaces.append(node)

    def skeletons(self, w):
        for node in self.interfaces:
            mods = fe.enclosing_modules(node)
            if mods:
                w("namespace POA_%s {" % mods[0])
                for m in mods[1:]:
                    w("namespace %s {" % cxx_name(m))
                w()
                cls = cxx_name(node.name)
            else:
                cls = "POA_" + node.name
            bases = self.bases(node)
            if bases:
                base_list = ", ".join("public virtual %s" % self.poa_scoped(b) for b in bases)
            else:
                base_list = "public virtual ::PortableServer::ServantBase"
            w("class %s : %s {" % (cls, base_list))
            w(" public:")
            w.indent()
            for _, method, ret, params, _, _, d in self.operations(node):
                w("virtual %s = 0;" % self.signature(method, ret, params, d))
            w()
            w("::IDL::traits<%s>::ref_type _this();" % self.scoped(node))
            w("bool _is_a(const std::string& repository_id) override;")
            w("const char* _rorb_repository_id() const override;")
            w(
                "rorb_status _rorb_dispatch(const char* op, size_t len, rorb_in* in,"
                " rorb_server_reply* reply) override;"
            )
            w.dedent()
            w()
            w(" protected:")
            w("  %s() = default;" % cls)
            w(
                "  bool %s(std::string_view op, rorb_in* in, rorb_server_reply* reply);"
                % self.ops_name(node)
            )
            w("};")
            w()
            if mods:
                for m in reversed(mods[1:]):
                    w("}  // namespace %s" % cxx_name(m))
                w("}  // namespace POA_%s" % mods[0])
                w()
        if self.interfaces:
            w("namespace CORBA {")
            w()
            for node in self.interfaces:
                w("template <> struct servant_traits<%s> {" % self.scoped(node))
                w("  using base_type = %s;" % self.poa_scoped(node))
                w("  using ref_type = ::CORBA::servant_reference<base_type>;")
                w("};")
                w()
            w("}  // namespace CORBA")
            w()

    def codec_declarations(self, w):
        typed = [
            n
            for n in self.typecodes
            if not fe.is_typedef(n)
        ]
        if not self.codecs and not typed:
            return
        w("namespace rustorb {")
        w("namespace cdr {")
        w()
        for node in typed:
            w("template <> struct type_code<%s> {" % self.scoped(node))
            w("  static %s get() { return %s(); }" % (TC_REF, self.tc_function(node)))
            w("};")
        if typed:
            w()
        for kind, node in self.codecs:
            t = self.scoped(node)
            if kind == "enum":
                w(
                    "template <> struct codec<%s> : enum_codec<%s, %d> {};"
                    % (t, t, len(node.values))
                )
                continue
            w("template <> struct codec<%s> {" % t)
            w("  static void write(rorb_out* out, const %s& v);" % t)
            w("  static void read(rorb_in* in, %s& v);" % t)
            w("};")
        w()
        w("}  // namespace cdr")
        w("}  // namespace rustorb")
        w()

    # -- the source ------------------------------------------------------

    def generate_source(self):
        """Call after generate_header, which collects what to define."""
        w = Writer()
        w(HEADER % self.idl_name)
        w('#include "%s%s"' % (self.base, self.opt.header_suffix))
        w()
        w("#include <memory>")
        w("#include <string_view>")
        w("#include <utility>")
        w()
        if self.interfaces:
            w("namespace {")
            for i, node in enumerate(self.interfaces):
                ids = [fe.repository_id(node)] + [
                    fe.repository_id(a) for a in self.ancestors(node)
                ]
                w(
                    'const ::rustorb::detail::InterfaceRegistration _rorb_registration_%d("%s", {%s});'
                    % (i, ids[0], ", ".join('"%s"' % x for x in ids))
                )
            w("}  // namespace")
            w()
        self.typecode_definitions(w)
        for node in self.values:
            self.value_source(w, node)
        self.value_registrations(w)
        for kind, node in self.codecs:
            if kind in ("struct", "exception"):
                self.struct_codec(w, node)
            elif kind == "union":
                self.union_codec(w, node)
        for node in self.interfaces:
            self.stub_source(w, node)
            self.skeleton_source(w, node)
        return w.text()

    def codec_of(self, t, where):
        return "::rustorb::cdr::codec<%s>" % self.ctype(t, where)

    def struct_codec(self, w, node):
        t = self.scoped(node)
        members = self.members(node)
        w("void rustorb::cdr::codec<%s>::write(rorb_out* out, const %s& v) {" % (t, t))
        for m, mt in members:
            w("  %s::write(out, v.%s());" % (self.codec_of(mt, node), cxx_name(m)))
        if not members:
            w("  (void)out;")
            w("  (void)v;")
        w("}")
        w()
        w("void rustorb::cdr::codec<%s>::read(rorb_in* in, %s& v) {" % (t, t))
        for m, mt in members:
            w("  %s::read(in, v.%s());" % (self.codec_of(mt, node), cxx_name(m)))
        if not members:
            w("  (void)in;")
            w("  (void)v;")
        w("}")
        w()

    def union_codec(self, w, node):
        t = self.scoped(node)
        disc, cases, _ = self.union_cases(node)
        dc = self.codec_of(disc, node)
        dt = self.ctype(disc, node)
        w("void rustorb::cdr::codec<%s>::write(rorb_out* out, const %s& v) {" % (t, t))
        w("  %s::write(out, v._d());" % dc)
        w("  switch (%s::_rorb_member(v._d())) {" % t)
        for i, (_, m, mt) in enumerate(cases):
            w(
                "    case %d: %s::write(out, v.%s()); break;"
                % (i, self.codec_of(mt, node), cxx_name(m))
            )
        w("    default: break;")
        w("  }")
        w("}")
        w()
        w("void rustorb::cdr::codec<%s>::read(rorb_in* in, %s& v) {" % (t, t))
        w("  %s d{};" % dt)
        w("  %s::read(in, d);" % dc)
        w("  if (rorb_in_failed(in)) return;")
        w("  v._rorb_reset(d);")
        w("  switch (%s::_rorb_member(d)) {" % t)
        for i, (_, m, mt) in enumerate(cases):
            w(
                "    case %d: %s::read(in, v.%s()); break;"
                % (i, self.codec_of(mt, node), cxx_name(m))
            )
        w("    default: break;")
        w("  }")
        w("}")
        w()

    def stub_source(self, w, node):
        cls = self.scoped(node)
        for op, method, ret, params, excs, oneway, d in self.operations(node):
            w("%s {" % self.signature(method, ret, params, d, cls[2:] + "::"))
            w.indent()
            if ret.kind != "void":
                w("%s _rorb_ret{};" % self.ctype(ret, d))
            ins = [(p, t) for p, t, dr in params if dr in ("in", "inout")]
            outs = [(p, t) for p, t, dr in params if dr in ("inout", "out")]
            exc_types = ", ".join(self.scoped(e) for e in excs)
            w(
                '::rustorb::detail::invoke<%s>(this, "%s", %s,'
                % (exc_types, op, "true" if oneway else "false")
            )
            w.indent()
            w.indent()
            if ins:
                w("[&](rorb_out* _out) {")
                for p, t in ins:
                    w("  %s::write(_out, %s);" % (self.codec_of(t, d), cxx_name(p)))
                w("},")
            else:
                w("::rustorb::detail::no_args(),")
            if ret.kind != "void" or outs:
                w("[&](rorb_in* _in) {")
                if ret.kind != "void":
                    w("  %s::read(_in, _rorb_ret);" % self.codec_of(ret, d))
                for p, t in outs:
                    w("  %s::read(_in, %s);" % (self.codec_of(t, d), cxx_name(p)))
                w("});")
            else:
                w("::rustorb::detail::no_results());")
            w.dedent()
            w.dedent()
            if ret.kind != "void":
                w("return _rorb_ret;")
            w.dedent()
            w("}")
            w()

    def skeleton_source(self, w, node):
        poa = self.poa_scoped(node)[2:]
        stub = self.scoped(node)
        w("::IDL::traits<%s>::ref_type %s::_this() {" % (stub, poa))
        w("  return ::IDL::traits<%s>::narrow(_rorb_this());" % stub)
        w("}")
        w()
        ids = [fe.repository_id(node)] + [fe.repository_id(a) for a in self.ancestors(node)]
        w("bool %s::_is_a(const std::string& repository_id) {" % poa)
        w('  return %s ||' % " ||\n         ".join('repository_id == "%s"' % i for i in ids))
        w('         repository_id == "IDL:omg.org/CORBA/Object:1.0";')
        w("}")
        w()
        w("const char* %s::_rorb_repository_id() const {" % poa)
        w('  return "%s";' % ids[0])
        w("}")
        w()
        w(
            "rorb_status %s::_rorb_dispatch(const char* op, size_t len, rorb_in* in,"
            " rorb_server_reply* reply) {" % poa
        )
        w("  std::string_view name(op, len);")
        w("  return ::rustorb::detail::upcall(reply, [&]() -> rorb_status {")
        for n in [node] + self.ancestors(node):
            w(
                "    if (%s::%s(name, in, reply)) return RORB_OK;"
                % (self.poa_scoped(n), self.ops_name(n))
            )
        w("    return ::rustorb::detail::bad_operation(reply);")
        w("  });")
        w("}")
        w()
        w(
            "bool %s::%s(std::string_view op, rorb_in* in, rorb_server_reply* reply) {"
            % (poa, self.ops_name(node))
        )
        w.indent()
        ops = self.operations(node)
        if not ops:
            w("(void)op;")
            w("(void)in;")
            w("(void)reply;")
        for opname, method, ret, params, excs, oneway, d in ops:
            w('if (op == "%s") {' % opname)
            w.indent()
            for p, t, dr in params:
                if dr in ("in", "inout"):
                    w("%s %s{};" % (self.ctype(t, d), cxx_name(p)))
                    w("%s::read(in, %s);" % (self.codec_of(t, d), cxx_name(p)))
            w("if (rorb_in_failed(in)) return true;")
            for p, t, dr in params:
                if dr == "out":
                    w("%s %s{};" % (self.ctype(t, d), cxx_name(p)))
            call = "this->%s(%s)" % (cxx_name(method), ", ".join(cxx_name(p) for p, _, _ in params))
            if excs:
                w("try {")
                w.indent()
            if ret.kind != "void":
                w("%s _rorb_ret = %s;" % (self.ctype(ret, d), call))
            else:
                w("%s;" % call)
            outs = [(p, t) for p, t, dr in params if dr in ("inout", "out")]
            if not oneway and (ret.kind != "void" or outs):
                w("::rustorb::detail::write_results([&] {")
                w.indent()
                w("rorb_out* _out = rorb_server_reply_output(reply);")
                if ret.kind != "void":
                    w("%s::write(_out, _rorb_ret);" % self.codec_of(ret, d))
                for p, t in outs:
                    w("%s::write(_out, %s);" % (self.codec_of(t, d), cxx_name(p)))
                w.dedent()
                w("});")
            if excs:
                w.dedent()
                for e in excs:
                    w("} catch (const %s& _e) {" % self.scoped(e))
                    w("  ::rustorb::detail::reply_user_exception(reply, _e);")
                w("}")
            w("return true;")
            w.dedent()
            w("}")
        w("return false;")
        w.dedent()
        w("}")
        w()


def fixed_text(value, digits, scale):
    """The decimal text of the constant ``value`` (a ``Decimal``) for a
    ``fixed<digits, scale>``; a value that does not fit is an error."""
    text = format(value, "f")
    negative = text.startswith("-")
    whole, _, frac = text.lstrip("-").partition(".")
    whole = whole.lstrip("0")
    frac = frac.rstrip("0")
    if len(whole) > digits - scale or len(frac) > scale:
        raise fe.GeneratorError("constant %s does not fit fixed<%d, %d>" % (text, digits, scale))
    return ("-" if negative and (whole or frac) else "") + (whole or "0") + ("." + frac if frac else "")


def _escape_char(c, wide):
    o = ord(c)
    if c == "'":
        return "\\'"
    if c == "\\":
        return "\\\\"
    if 0x20 <= o < 0x7F:
        return c
    if o < 0x100 and not wide:
        return "\\%03o" % o
    if o < 0x80:
        return "\\%03o" % o
    return "\\U%08X" % o


def _escape_string(s, wide):
    out = []
    for c in s:
        o = ord(c)
        if c == '"':
            out.append('\\"')
        elif c == "\\":
            out.append("\\\\")
        elif 0x20 <= o < 0x7F:
            out.append(c)
        elif wide:
            out.append("\\%03o" % o if o < 0x80 else "\\U%08X" % o)
        else:
            out.extend("\\%03o" % b for b in c.encode("utf-8"))
    return "".join(out)


def _resolve_exceptions(node, names):
    out = []
    for n in names or []:
        if hasattr(n, "repository_id"):
            out.append(n)
            continue
        found = (
            node.root_node.find_exceptions(str(n), scope=node)
            if hasattr(node.root_node, "find_exceptions")
            else []
        )
        if not found:
            raise fe.GeneratorError("Can not find the exception %s" % n, node)
        out.append(found[0])
    return out


def write_outputs(backend, outdir):
    """Write the header and the source for the IDL file of ``backend``
    under ``outdir``; return the paths written."""
    header = backend.generate_header()
    source = backend.generate_source()
    os.makedirs(outdir, exist_ok=True)
    written = []
    for suffix, text in (
        (backend.opt.header_suffix, header),
        (backend.opt.source_suffix, source),
    ):
        path = os.path.join(outdir, backend.base + suffix)
        tmp = path + ".tmp"
        with open(tmp, "w") as f:
            f.write(text)
        os.replace(tmp, path)
        written.append(path)
    return written
