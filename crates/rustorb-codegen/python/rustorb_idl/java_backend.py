"""The Java backend: ``rustorb-idl -bjava``.

Writes one ``.java`` file per class, in the directories of their packages
under the output directory, following the IDL to Java mapping:

- modules are packages, and the types defined inside an interface,
  struct, union or exception ``X`` are in the package ``XPackage``;
- structs, unions, enums and exceptions are classes, with a ``Helper``
  (``read``, ``write``, ``insert``, ``extract``, ``type``, ``id``) and a
  ``Holder``; typedefs get a ``Helper``, and a ``Holder`` when they name a
  sequence or an array;
- an interface ``I`` is the signature interface ``I``, the operations
  interface ``IOperations``, the stub ``_IStub``, the skeleton ``IPOA``
  and its tie ``IPOATie``, ``IHelper`` and ``IHolder``.

The classes use only the standard API of the mapping (``org.omg.CORBA``
and ``org.omg.PortableServer``), except for what the stubs call to invoke
and what the Helpers call to put values in anys (``org.rustorb.Stubs``,
``org.rustorb.Call``, ``org.rustorb.Anys``), all in the rustorb runtime
(``java/``, MIT OR Apache-2.0). ``fixed<d, s>`` is ``java.math.BigDecimal``,
read and written with ``read_fixed(d, s)`` / ``write_fixed(v, d, s)``.

A valuetype ``V`` is the class ``V`` (a ``StreamableValue``, abstract for
an abstract valuetype, which is an interface), ``VHelper``, ``VHolder`` and
``VDefaultFactory``, which the ORB finds by name. A value box of a basic
type is a class with a public ``value``; a box of another type is that
type itself, and its Helper is a ``BoxedValueHelper``. A custom valuetype
is an abstract class implementing ``CustomValue``. A valuetype with
operations or attributes, or that supports interfaces, is an abstract class
(implementing the ``IOperations`` of the interfaces, so that its servant is
their tie) without a default factory; one with initializers has a
``VValueFactory`` interface for the application's factory. Abstract
interfaces are not mapped yet.

``-Wbpackage=PKG`` puts every package under ``PKG`` (and the definitions
outside modules in ``PKG``).
"""

