def java_name(name):
    """An IDL identifier as a Java identifier: Java keywords (and the
    methods of java.lang.Object) get a leading ``_``, as the mapping says."""
    if name in JAVA_KEYWORDS:
        return "_" + name
    return name


class Writer(cxx_backend.Writer):
    def __call__(self, text=""):
        if text:
            self.lines.append("    " * self.level + text)
        else:
            self.lines.append("")


class Options(object):
    def __init__(self):
        # The package prefix (-Wbpackage=a.b): every package is under it,
        # and the definitions outside modules are in it rather than in the
        # unnamed package (which a named package cannot use).
        self.package = ""


class JavaBackend(object):
    LANGUAGE = "Java"

    def __init__(self, spec, options=None):
        self.spec = spec
        self.opt = options or Options()
        self.idl_name = os.path.basename(spec.path)
        # (package, class name) -> text
        self.files = {}

    # -- names -----------------------------------------------------------

    def package_of(self, node):
        """The Java package of a definition (a tuple of names)."""
        parts = []
        n = node.parent
        chain = []
        while n is not None and n.parent is not None:
            chain.append(n)
            n = n.parent
        for s in reversed(chain):
            if fe.is_module(s):
                parts.append(java_name(s.name))
            else:
                parts.append(java_name(s.name) + "Package")
        prefix = tuple(p for p in getattr(self.opt, "package", "").split(".") if p)
        return prefix + tuple(parts)

    def scoped(self, node, suffix=""):
        """The fully qualified Java name of a definition."""
        return ".".join(self.package_of(node) + (java_name(node.name) + suffix,))

    # -- types -----------------------------------------------------------

    def full(self, node):
        return cxx_backend.CxxBackend.full(self, node)

    def box_class(self, node):
        """Whether a value box has a class of its own (a box of a basic
        type), rather than being the boxed Java type."""
        return fe.type_of(node.boxed_type, node).resolved().kind in BASIC

    def jtype(self, t, where=None):
        """The Java type of a :class:`frontend.Type`."""
        k = t.kind
        if k in BASIC:
            return BASIC[k]
        if k in UNSUPPORTED:
            raise fe.GeneratorError(
                "%s is not supported by the Java backend yet" % UNSUPPORTED[k], where
            )
        if k == "void":
            return "void"
        if k in ("string", "wstring"):
            return "String"
        if k == "any":
            return "org.omg.CORBA.Any"
        if k == "TypeCode":
            return "org.omg.CORBA.TypeCode"
        if k == "Object":
            return "org.omg.CORBA.Object"
        if k in ("sequence", "array"):
            return self.jtype(t.content, where) + "[]"
        if k == "fixed":
            return "java.math.BigDecimal"
        if k == "named":
            n = self.full(t.node)
            if fe.is_native(n):
                raise fe.GeneratorError("native %s cannot be used in Java" % n.name, where)
            if fe.is_typedef(n):
                return self.jtype(fe.type_of(n.type, n), where)
            if fe.is_valuetype(n) and n.is_boxed and not self.box_class(n):
                return self.jtype(fe.type_of(n.boxed_type, n), where)
            return self.scoped(n)
        raise fe.GeneratorError("no Java type for %r" % t, where)

    def holder(self, t, where=None):
        """The Holder class of a type, for out and inout parameters."""
        if t.kind == "named":
            n = self.full(t.node)
            if fe.is_typedef(n):
                if self.has_holder(n):
                    return self.scoped(n, "Holder")
                return self.holder(fe.type_of(n.type, n), where)
            return self.scoped(n, "Holder")
        if t.kind in HOLDER:
            return HOLDER[t.kind]
        self.jtype(t, where)  # raises for the unsupported ones
        raise fe.GeneratorError(
            "an anonymous %s cannot be an out or inout parameter" % t.kind, where
        )

    def has_holder(self, typedef):
        r = fe.type_of(typedef.type, typedef).resolved()
        return r.kind in ("sequence", "array")

    def new_array(self, t, length):
        """``new T[length]`` for an array of the Java type of element t."""
        base = self.jtype(t)
        dims = ""
        while base.endswith("[]"):
            base = base[:-2]
            dims += "[]"
        return "new %s[%s]%s" % (base, length, dims)

    # -- values ----------------------------------------------------------

    def literal(self, value, t):
        """A Java expression for a constant of type ``t``."""
        r = t.resolved()
        k = r.kind
        if k == "named" and fe.is_enum(r.node):
            return "%s.%s" % (self.scoped(r.node), java_name(value.name))
        if k == "boolean":
            return "true" if value else "false"
        if k in ("float", "double", "longdouble"):
            v = float(value)
            box = "Float" if k == "float" else "Double"
            if v != v:
                return "%s.NaN" % box
            if v in (float("inf"), float("-inf")):
                return "%s.%s_INFINITY" % (box, "NEGATIVE" if v < 0 else "POSITIVE")
            expr = repr(v)
            return expr + ("f" if k == "float" else "")
        if k in ("char", "wchar"):
            c = value if isinstance(value, str) else chr(value)
            return "'%s'" % _escape(c, "'")
        if k in ("string", "wstring"):
            return '"%s"' % "".join(_escape(c, '"') for c in str(value))
        if k == "fixed":
            whole, _, frac = cxx_backend.fixed_text(value, r.digits, r.scale).partition(".")
            text = whole + ("." + frac.ljust(r.scale, "0") if r.scale else "")
            return 'new java.math.BigDecimal("%s")' % text
        if k in INT_RANGES:
            v = int(value)
            lo, hi = INT_RANGES[k]
            if v < lo or v > hi:
                raise fe.GeneratorError("constant %d out of range for %s" % (v, k))
            if k in ("longlong", "ulonglong"):
                if v >= 1 << 63:
                    v -= 1 << 64
                if v == -(1 << 63):
                    return "Long.MIN_VALUE"
                return "%dL" % v
            if k in ("long", "ulong"):
                if v >= 1 << 31:
                    v -= 1 << 32
                if v == -(1 << 31):
                    return "Integer.MIN_VALUE"
                return "%d" % v
            if k in ("short", "ushort"):
                if v >= 1 << 15:
                    v -= 1 << 16
                return "(short) %d" % v
            if k == "octet":
                if v >= 128:
                    v -= 256
                return "(byte) %d" % v
        raise fe.GeneratorError("no Java literal for a constant of type %r" % r)

    # -- marshalling -----------------------------------------------------

    def write(self, w, t, expr, depth=0, where=None):
        """Statements that write ``expr`` of type ``t`` to ``$out``."""
        k = t.kind
        if k in STREAM:
            w("$out.write_%s(%s);" % (STREAM[k], expr))
        elif k in ("string", "wstring"):
            if t.bound:
                w("if (%s.length() > %d) {" % (expr, t.bound))
                w("    throw new org.omg.CORBA.BAD_PARAM(\"string longer than its bound\", 0,")
                w("            org.omg.CORBA.CompletionStatus.COMPLETED_NO);")
                w("}")
            w("$out.write_%s(%s);" % (k, expr))
        elif k == "fixed":
            w("$out.write_fixed(%s, (short) %d, (short) %d);" % (expr, t.digits, t.scale))
        elif k == "any":
            w("$out.write_any(%s);" % expr)
        elif k == "TypeCode":
            w("$out.write_TypeCode(%s);" % expr)
        elif k == "Object":
            w("$out.write_Object(%s);" % expr)
        elif k == "sequence":
            if t.bound:
                w("if (%s.length > %d) {" % (expr, t.bound))
                w("    throw new org.omg.CORBA.BAD_PARAM(\"sequence longer than its bound\", 0,")
                w("            org.omg.CORBA.CompletionStatus.COMPLETED_NO);")
                w("}")
            w("$out.write_ulong(%s.length);" % expr)
            self.write_elements(w, t.content, expr, "%s.length" % expr, depth, where)
        elif k == "array":
            w("if (%s.length != %d) {" % (expr, t.length))
            w("    throw new org.omg.CORBA.BAD_PARAM(\"array of the wrong length\", 0,")
            w("            org.omg.CORBA.CompletionStatus.COMPLETED_NO);")
            w("}")
            self.write_elements(w, t.content, expr, str(t.length), depth, where)
        elif k == "named":
            n = self.full(t.node)
            if fe.is_native(n):
                raise fe.GeneratorError("native %s cannot be used in Java" % n.name, where)
            w("%s.write($out, %s);" % (self.scoped(n, "Helper"), expr))
        else:
            self.jtype(t, where)
            raise fe.GeneratorError("cannot write %r" % t, where)

    def write_elements(self, w, content, expr, length, depth, where):
        c = content
        if c.kind in STREAM and c.kind not in ("boolean", "char", "wchar", "longdouble"):
            w("$out.write_%s_array(%s, 0, %s);" % (STREAM[c.kind], expr, length))
            return
        i = "$i%d" % depth
        w("for (int %s = 0; %s < %s; %s++) {" % (i, i, length, i))
        w.indent()
        self.write(w, c, "%s[%s]" % (expr, i), depth + 1, where)
        w.dedent()
        w("}")

    def read(self, w, t, target, depth=0, where=None):
        """Statements that read a value of type ``t`` from ``$in`` into
        ``target``."""
        k = t.kind
        if k in STREAM:
            w("%s = $in.read_%s();" % (target, STREAM[k]))
        elif k in ("string", "wstring"):
            w("%s = $in.read_%s();" % (target, k))
            if t.bound:
                w("if (%s.length() > %d) {" % (target, t.bound))
                w("    throw new org.omg.CORBA.MARSHAL(\"string longer than its bound\", 0,")
                w("            org.omg.CORBA.CompletionStatus.COMPLETED_MAYBE);")
                w("}")
        elif k == "fixed":
            w("%s = $in.read_fixed((short) %d, (short) %d);" % (target, t.digits, t.scale))
        elif k == "any":
            w("%s = $in.read_any();" % target)
        elif k == "TypeCode":
            w("%s = $in.read_TypeCode();" % target)
        elif k == "Object":
            w("%s = $in.read_Object();" % target)
        elif k == "sequence":
            n = "$n%d" % depth
            w("{")
            w.indent()
            w("int %s = org.rustorb.Stubs.readLength($in, %d);" % (n, self.min_size(t.content)))
            if t.bound:
                w("if (%s > %d) {" % (n, t.bound))
                w("    throw new org.omg.CORBA.MARSHAL(\"sequence longer than its bound\", 0,")
                w("            org.omg.CORBA.CompletionStatus.COMPLETED_MAYBE);")
                w("}")
            w("%s = %s;" % (target, self.new_array(t.content, n)))
            self.read_elements(w, t.content, target, n, depth, where)
            w.dedent()
            w("}")
        elif k == "array":
            w("%s = %s;" % (target, self.new_array(t.content, t.length)))
            self.read_elements(w, t.content, target, str(t.length), depth, where)
        elif k == "named":
            n = self.full(t.node)
            if fe.is_native(n):
                raise fe.GeneratorError("native %s cannot be used in Java" % n.name, where)
            w("%s = %s.read($in);" % (target, self.scoped(n, "Helper")))
        else:
            self.jtype(t, where)
            raise fe.GeneratorError("cannot read %r" % t, where)

    def read_elements(self, w, content, target, length, depth, where):
        c = content
        if c.kind in STREAM and c.kind not in ("boolean", "char", "wchar", "longdouble"):
            w("$in.read_%s_array(%s, 0, %s);" % (STREAM[c.kind], target, length))
            return
        i = "$i%d" % depth
        w("for (int %s = 0; %s < %s; %s++) {" % (i, i, length, i))
        w.indent()
        self.read(w, c, "%s[%s]" % (target, i), depth + 1, where)
        w.dedent()
        w("}")

    def min_size(self, t):
        r = t.resolved()
        if r.kind in MIN_SIZE:
            return MIN_SIZE[r.kind]
        if r.kind == "named" and fe.is_enum(r.node):
            return 4
        if r.kind == "named" and fe.is_interface(r.node) and not self.is_abstract(r.node):
            return 4
        return 1

    # -- TypeCodes -------------------------------------------------------

    def tc_expr(self, t, where=None):
        """A Java expression for the TypeCode of ``t``."""
        k = t.kind
        if k in TCKIND:
            return "%s.get_primitive_tc(org.omg.CORBA.TCKind.%s)" % (ORB, TCKIND[k])
        if k == "string":
            return "%s.create_string_tc(%d)" % (ORB, t.bound)
        if k == "wstring":
            return "%s.create_wstring_tc(%d)" % (ORB, t.bound)
        if k == "Object":
            return "org.omg.CORBA.ObjectHelper.type()"
        if k == "fixed":
            return "%s.create_fixed_tc((short) %d, (short) %d)" % (ORB, t.digits, t.scale)
        if k == "sequence":
            return "%s.create_sequence_tc(%d, %s)" % (ORB, t.bound, self.tc_expr(t.content, where))
        if k == "array":
            return "%s.create_array_tc(%d, %s)" % (ORB, t.length, self.tc_expr(t.content, where))
        if k == "named":
            n = self.full(t.node)
            if fe.is_native(n):
                raise fe.GeneratorError("native %s cannot be used in Java" % n.name, where)
            return "%s.type()" % self.scoped(n, "Helper")
        self.jtype(t, where)
        raise fe.GeneratorError("no TypeCode for %r" % t, where)

    # -- files -----------------------------------------------------------

    def add(self, node, name, text):
        """Adds the class ``name`` in the package of ``node``."""
        pkg = self.package_of(node)
        w = Writer()
        w(HEADER % self.idl_name)
        if pkg:
            w("package %s;" % ".".join(pkg))
            w()
        out = w.text() + text
        self.files[(pkg, name)] = out

    def generate(self):
        """Every class of the file, as ``{(package, class): text}``."""
        for it in fe.definitions(self.spec):
            n = it.node
            if fe.is_module(n) or fe.is_operation(n) or fe.is_attribute(n):
                continue
            self.definition(n)
        return self.files

    def definition(self, node):
        if fe.is_const(node):
            if not fe.is_interface(node.parent):
                self.module_const(node)
        elif fe.is_enum(node):
            self.enum(node)
        elif fe.is_typedef(node):
            self.typedef(node)
        elif fe.is_exception(node):
            self.struct(node, exception=True)
        elif fe.is_struct(node):
            if not fe.is_forward(node):
                self.struct(node)
        elif fe.is_union(node):
            if not fe.is_forward(node):
                self.union(node)
        elif fe.is_interface(node):
            if not fe.is_forward(node):
                self.interface(node)
        elif fe.is_native(node):
            pass
        elif fe.is_valuetype(node):
            if fe.is_forward(node):
                pass
            elif node.is_boxed:
                self.value_box(node)
            else:
                self.valuetype(node)
        else:
            raise fe.GeneratorError(
                "%s definitions are not supported yet" % fe.kind_name(node), node
            )

    def nested(self, scope):
        """The types defined inside a struct, union, exception or
        interface (in the package ``<name>Package``)."""
        for d in fe.members_of(scope):
            if fe.is_operation(d) or fe.is_attribute(d) or fe.is_const(d):
                continue
            if hasattr(d, "is_public"):  # a state member of a valuetype
                continue
            if d in getattr(scope, "factories", ()):  # an initializer
                continue
            self.definition(d)

    # constants

    def module_const(self, node):
        t = fe.type_of(node.type, node)
        name = java_name(node.name)
        w = Writer()
        w("public interface %s {" % name)
        w("    %s value = %s;" % (self.jtype(t, node), self.literal(node.value, t)))
        w("}")
        self.add(node, name, w.text())

    # Helpers and Holders

    def helper(self, node, jtype, tc_body, write_body, read_body, extra=None,
               exception=False):
        """The Helper class of ``node``: ``tc_body(w)`` sets ``__typeCode``,
        ``write_body(w)`` writes ``value`` to ``$out`` and ``read_body(w)``
        reads ``$result`` from ``$in``."""
        name = java_name(node.name)
        w = Writer()
        w("public abstract class %sHelper {" % name)
        w.indent()
        w('private static final String _id = "%s";' % fe.repository_id(node))
        w("private static volatile org.omg.CORBA.TypeCode __typeCode;")
        w("private static boolean __active;")
        w()
        insert = "insertException" if exception else "insert"
        extract = "extractException" if exception else "extract"
        w("public static void insert(org.omg.CORBA.Any a, %s that) {" % jtype)
        w("    org.rustorb.Anys.%s(a, type(), $out -> write($out, that));" % insert)
        w("}")
        w()
        w("public static %s extract(org.omg.CORBA.Any a) {" % jtype)
        w("    return org.rustorb.Anys.%s(a, type(), %sHelper::read);" % (extract, name))
        w("}")
        w()
        w("public static org.omg.CORBA.TypeCode type() {")
        w("    if (__typeCode == null) {")
        w("        synchronized (org.omg.CORBA.TypeCode.class) {")
        w("            if (__typeCode == null) {")
        w("                if (__active) {")
        w("                    return %s.create_recursive_tc(_id);" % ORB)
        w("                }")
        w("                __active = true;")
        w("                try {")
        w.level += 5
        tc_body(w)
        w.level -= 5
        w("                } finally {")
        w("                    __active = false;")
        w("                }")
        w("            }")
        w("        }")
        w("    }")
        w("    return __typeCode;")
        w("}")
        w()
        w("public static String id() {")
        w("    return _id;")
        w("}")
        w()
        w("public static %s read(%s $in) {" % (jtype, IN))
        w.indent()
        read_body(w)
        w.dedent()
        w("}")
        w()
        w("public static void write(%s $out, %s value) {" % (OUT, jtype))
        w.indent()
        write_body(w)
        w.dedent()
        w("}")
        if extra:
            w()
            extra(w)
        w.dedent()
        w("}")
        self.add(node, name + "Helper", w.text())

    def holder_class(self, node, jtype, init="null"):
        name = java_name(node.name)
        helper = name + "Helper"
        w = Writer()
        w("public final class %sHolder implements org.omg.CORBA.portable.Streamable {" % name)
        w.indent()
        w("public %s value = %s;" % (jtype, init))
        w()
        w("public %sHolder() {}" % name)
        w()
        w("public %sHolder(%s initialValue) {" % (name, jtype))
        w("    value = initialValue;")
        w("}")
        w()
        w("@Override")
        w("public void _read(%s i) {" % IN)
        w("    value = %s.read(i);" % helper)
        w("}")
        w()
        w("@Override")
        w("public void _write(%s o) {" % OUT)
        w("    %s.write(o, value);" % helper)
        w("}")
        w()
        w("@Override")
        w("public org.omg.CORBA.TypeCode _type() {")
        w("    return %s.type();" % helper)
        w("}")
        w.dedent()
        w("}")
        self.add(node, name + "Holder", w.text())

    # enums

    def enum(self, node):
        name = java_name(node.name)
        items = [java_name(v.name) for v in node.values]
        w = Writer()
        w("public class %s implements org.omg.CORBA.portable.IDLEntity {" % name)
        w.indent()
        w("private static final long serialVersionUID = 1L;")
        w("private static final int __size = %d;" % len(items))
        w("private static final %s[] __array = new %s[__size];" % (name, name))
        w()
        for i, it in enumerate(items):
            w("public static final int _%s = %d;" % (it, i))
            w("public static final %s %s = new %s(_%s);" % (name, it, name, it))
        w()
        w("private final int __value;")
        w()
        w("public int value() {")
        w("    return __value;")
        w("}")
        w()
        w("public static %s from_int(int value) {" % name)
        w("    if (value >= 0 && value < __size) {")
        w("        return __array[value];")
        w("    }")
        w("    throw new org.omg.CORBA.BAD_PARAM();")
        w("}")
        w()
        w("protected %s(int value) {" % name)
        w("    __value = value;")
        w("    __array[__value] = this;")
        w("}")
        w()
        w("private java.lang.Object readResolve() {")
        w("    return from_int(__value);")
        w("}")
        w()
        w("@Override")
        w("public String toString() {")
        w('    return new String[] {%s}[__value];' % ", ".join('"%s"' % v.name for v in node.values))
        w("}")
        w.dedent()
        w("}")
        self.add(node, name, w.text())
        scoped = self.scoped(node)

        def tc(w):
            w(
                '__typeCode = %s.create_enum_tc(_id, "%s", new String[] {%s});'
                % (ORB, node.name, ", ".join('"%s"' % v.name for v in node.values))
            )

        self.helper(
            node,
            scoped,
            tc,
            lambda w: w("$out.write_ulong(value.value());"),
            lambda w: w("return %s.from_int($in.read_ulong());" % scoped),
        )
        self.holder_class(node, scoped)

    # typedefs

    def typedef(self, node):
        t = fe.type_of(node.type, node)
        jtype = self.jtype(t, node)

        def tc(w):
            w(
                '__typeCode = %s.create_alias_tc(_id, "%s", %s);'
                % (ORB, node.name, self.tc_expr(t, node))
            )

        def write_body(w):
            self.write(w, t, "value", 0, node)

        def read_body(w):
            w("%s $result;" % jtype)
            self.read(w, t, "$result", 0, node)
            w("return $result;")

        self.helper(node, jtype, tc, write_body, read_body)
        if self.has_holder(node):
            self.holder_class(node, jtype)

    # structs and exceptions

    def members(self, node):
        return cxx_backend.CxxBackend.members(self, node)

    def struct(self, node, exception=False):
        name = java_name(node.name)
        members = self.members(node)
        w = Writer()
        if exception:
            w("public final class %s extends org.omg.CORBA.UserException {" % name)
        else:
            w("public final class %s implements org.omg.CORBA.portable.IDLEntity {" % name)
        w.indent()
        w("private static final long serialVersionUID = 1L;")
        w()
        for m, t in members:
            w("public %s %s;" % (self.jtype(t, node), java_name(m)))
        if members:
            w()
        sup = "super(%sHelper.id());" % name if exception else None
        w("public %s() {" % name)
        if sup:
            w("    " + sup)
        w("}")
        if members:
            params = ", ".join("%s %s" % (self.jtype(t, node), java_name(m)) for m, t in members)
            w()
            w("public %s(%s) {" % (name, params))
            if sup:
                w("    " + sup)
            for m, _ in members:
                w("    this.%s = %s;" % (java_name(m), java_name(m)))
            w("}")
        if exception:
            params = "".join(", %s %s" % (self.jtype(t, node), java_name(m)) for m, t in members)
            w()
            w("public %s(String $reason%s) {" % (name, params))
            w('    super(%sHelper.id() + "  " + $reason);' % name)
            for m, _ in members:
                w("    this.%s = %s;" % (java_name(m), java_name(m)))
            w("}")
        w.dedent()
        w("}")
        self.add(node, name, w.text())
        scoped = self.scoped(node)

        def tc(w):
            w("org.omg.CORBA.StructMember[] $members = {")
            for m, t in members:
                w('    new org.omg.CORBA.StructMember("%s", %s, null),' % (m, self.tc_expr(t, node)))
            w("};")
            w(
                '__typeCode = %s.create_%s_tc(_id, "%s", $members);'
                % (ORB, "exception" if exception else "struct", node.name)
            )

        def write_body(w):
            if exception:
                w("$out.write_string(id());")
            for m, t in members:
                self.write(w, t, "value.%s" % java_name(m), 0, node)

        def read_body(w):
            w("%s $result = new %s();" % (scoped, scoped))
            if exception:
                w("// the repository id")
                w("$in.read_string();")
            for m, t in members:
                self.read(w, t, "$result.%s" % java_name(m), 0, node)
            w("return $result;")

        self.helper(node, scoped, tc, write_body, read_body, exception=exception)
        self.holder_class(node, scoped)
        self.nested(node)

    # valuetypes

    def prefix_registration(self, w):
        """A static initialiser that makes the package prefix known to the
        ORB, which finds generated classes by repository id."""
        if self.opt.package:
            w("static {")
            w('    org.rustorb.Values.addPackage("%s.");' % self.opt.package)
            w("}")
            w()

    def valuetype(self, node):
        cxx_backend.CxxBackend.check_value(self, node)
        name = java_name(node.name)
        scoped = self.scoped(node)
        base = fe.concrete_base(node)
        abstract_bases = [self.full(b) for b in fe.value_bases(node) if b.is_abstract]
        members = cxx_backend.CxxBackend.state_members(self, node)
        w = Writer()
        if node.is_abstract:
            ext = [self.scoped(b) for b in abstract_bases] or ["org.omg.CORBA.portable.ValueBase"]
            ext += self.supported_operations(node)
            w("public interface %s extends %s {" % (name, ", ".join(ext)))
            w.indent()
            self.value_methods(w, node, "")
            w.dedent()
            w("}")
            self.add(node, name, w.text())
        elif node.is_custom:
            self.custom_value(node, name, base, abstract_bases, members)
        else:
            behaviour = fe.has_behaviour(node)
            impl = (
                ["org.omg.CORBA.portable.StreamableValue"]
                + [self.scoped(b) for b in abstract_bases]
                + self.supported_operations(node)
            )
            head = "public %sclass %s" % ("abstract " if behaviour else "", name)
            if base is not None:
                head += " extends %s" % self.scoped(self.full(base))
            w("%s implements %s {" % (head, ", ".join(impl)))
            w.indent()
            w("private static final long serialVersionUID = 1L;")
            w(
                "private static final String[] _rorb_truncatable_ids = {%s};"
                % ", ".join('"%s"' % i for i in cxx_backend.CxxBackend.sent_ids(self, node))
            )
            w()
            for m, t, public in members:
                w("%s %s %s;" % ("public" if public else "protected", self.jtype(t, node), java_name(m)))
            if members:
                w()
            w("public %s() {}" % name)
            w()
            self.value_methods(w, node)
            w("@Override")
            w("public String[] _truncatable_ids() {")
            w("    return _rorb_truncatable_ids;")
            w("}")
            w()
            w("@Override")
            w("public void _read(%s $in) {" % IN)
            w.indent()
            if base is not None:
                w("super._read($in);")
            for m, t, _ in members:
                self.read(w, t, "this.%s" % java_name(m), 0, node)
            w.dedent()
            w("}")
            w()
            w("@Override")
            w("public void _write(%s $out) {" % OUT)
            w.indent()
            if base is not None:
                w("super._write($out);")
            for m, t, _ in members:
                self.write(w, t, "this.%s" % java_name(m), 0, node)
            w.dedent()
            w("}")
            w()
            w("@Override")
            w("public org.omg.CORBA.TypeCode _type() {")
            w("    return %sHelper.type();" % name)
            w("}")
            w.dedent()
            w("}")
            self.add(node, name, w.text())

        if node.factories:
            self.value_factory(node, name)
        if not node.is_abstract and not node.is_custom and not fe.has_behaviour(node):
            # the default factory, found by the ORB by its name
            w = Writer()
            w(
                "public class %sDefaultFactory implements org.omg.CORBA.portable.ValueFactory {"
                % name
            )
            w.indent()
            w("@Override")
            w(
                "public java.io.Serializable read_value("
                "org.omg.CORBA_2_3.portable.InputStream is) {"
            )
            w("    return is.read_value(new %s());" % scoped)
            w("}")
            w.dedent()
            w("}")
            self.add(node, name + "DefaultFactory", w.text())

        def tc(w):
            w("org.omg.CORBA.ValueMember[] $members = {")
            for m, t, public in members:
                w(
                    '    new org.omg.CORBA.ValueMember("%s", "", "", "", %s, null, '
                    "org.omg.CORBA.%s.value),"
                    % (m, self.tc_expr(t, node), "PUBLIC_MEMBER" if public else "PRIVATE_MEMBER")
                )
            w("};")
            w(
                '__typeCode = %s.create_value_tc(_id, "%s", org.omg.CORBA.%s.value, %s, $members);'
                % (
                    ORB,
                    node.name,
                    cxx_backend.CxxBackend.value_modifier(self, node),
                    self.tc_expr(fe.Type("named", node=base), node) if base is not None else "null",
                )
            )

        def write_body(w):
            w(
                "((org.omg.CORBA_2_3.portable.OutputStream) $out).write_value(value, _id);"
            )

        def read_body(w):
            w(
                "java.io.Serializable $v = "
                "((org.omg.CORBA_2_3.portable.InputStream) $in).read_value(_id);"
            )
            w("if ($v != null && !($v instanceof %s)) {" % scoped)
            w("    throw new org.omg.CORBA.MARSHAL(\"not a %s: \" + $v, 0," % node.name)
            w("            org.omg.CORBA.CompletionStatus.COMPLETED_MAYBE);")
            w("}")
            w("return (%s) $v;" % scoped)

        self.helper(node, scoped, tc, write_body, read_body, extra=self.prefix_registration)
        self.holder_class(node, scoped)
        self.nested(node)

    def supported_operations(self, node):
        """The operations interfaces of the interfaces a valuetype supports,
        which its class implements (its servant is their tie), and the
        abstract interfaces it supports, whose values it is."""
        return [
            self.scoped(i) if i.is_abstract else self.scoped(i, "Operations")
            for i in fe.supported_interfaces(node)
        ]

    def value_methods(self, w, node, prefix="public abstract "):
        """The operations and attributes of a valuetype, as abstract methods
        of its class (or methods of its interface)."""
        for opname, method, ret, params, excs, _, d in self.operations(node):
            if opname.startswith("_set_"):
                t = params[0][1]
                w("%svoid %s(%s value);" % (prefix, java_name(method), self.jtype(t, d)))
            else:
                w("%s%s;" % (prefix, self.signature(method, ret, params, excs, d)))
            w()

    def value_factory(self, node, name):
        """VValueFactory, the factory of a valuetype with initializers: the
        application implements it and registers it."""
        w = Writer()
        w(
            "public interface %sValueFactory extends org.omg.CORBA.portable.ValueFactory {"
            % name
        )
        w.indent()
        for f in node.factories:
            params = [(a.name, fe.type_of(a.type, a), "in") for a in f.arguments]
            w(
                "%s;"
                % self.signature(f.name, fe.Type("named", node=node), params, [], node)
            )
        w.dedent()
        w("}")
        self.add(node, name + "ValueFactory", w.text())

    def custom_value(self, node, name, base, abstract_bases, members):
        """A custom valuetype: an abstract class with the state members,
        whose implementation provides marshal and unmarshal and registers a
        value factory."""
        impl = (
            ["org.omg.CORBA.portable.CustomValue"]
            + [self.scoped(b) for b in abstract_bases]
            + self.supported_operations(node)
        )
        head = "public abstract class %s" % name
        if base is not None:
            head += " extends %s" % self.scoped(self.full(base))
        w = Writer()
        w("%s implements %s {" % (head, ", ".join(impl)))
        w.indent()
        w("private static final long serialVersionUID = 1L;")
        w(
            "private static final String[] _rorb_truncatable_ids = {%s};"
            % ", ".join('"%s"' % i for i in cxx_backend.CxxBackend.sent_ids(self, node))
        )
        w()
        for m, t, public in members:
            w("%s %s %s;" % ("public" if public else "protected", self.jtype(t, node), java_name(m)))
        if members:
            w()
        self.value_methods(w, node)
        w("@Override")
        w("public String[] _truncatable_ids() {")
        w("    return _rorb_truncatable_ids;")
        w("}")
        w()
        w("public org.omg.CORBA.TypeCode _type() {")
        w("    return %sHelper.type();" % name)
        w("}")
        w.dedent()
        w("}")
        self.add(node, name, w.text())

    def value_box(self, node):
        name = java_name(node.name)
        t = fe.type_of(node.boxed_type, node)
        own = self.box_class(node)
        jtype = self.scoped(node) if own else self.jtype(t, node)
        if own:
            w = Writer()
            w("public class %s implements org.omg.CORBA.portable.ValueBase {" % name)
            w.indent()
            w("private static final long serialVersionUID = 1L;")
            w('private static final String[] _rorb_truncatable_ids = {"%s"};' % fe.repository_id(node))
            w()
            w("public %s value;" % self.jtype(t, node))
            w()
            w("public %s(%s initial) {" % (name, self.jtype(t, node)))
            w("    value = initial;")
            w("}")
            w()
            w("@Override")
            w("public String[] _truncatable_ids() {")
            w("    return _rorb_truncatable_ids;")
            w("}")
            w.dedent()
            w("}")
            self.add(node, name, w.text())

        w = Writer()
        w("public final class %sHelper implements org.omg.CORBA.portable.BoxedValueHelper {" % name)
        w.indent()
        w('private static final String _id = "%s";' % fe.repository_id(node))
        w("private static volatile org.omg.CORBA.TypeCode __typeCode;")
        w()
        self.prefix_registration(w)
        w("public static void insert(org.omg.CORBA.Any a, %s that) {" % jtype)
        w("    org.rustorb.Anys.insert(a, type(), $out -> write($out, that));")
        w("}")
        w()
        w("public static %s extract(org.omg.CORBA.Any a) {" % jtype)
        w("    return org.rustorb.Anys.extract(a, type(), %sHelper::read);" % name)
        w("}")
        w()
        w("public static org.omg.CORBA.TypeCode type() {")
        w("    if (__typeCode == null) {")
        w("        synchronized (org.omg.CORBA.TypeCode.class) {")
        w("            if (__typeCode == null) {")
        w(
            '                __typeCode = %s.create_value_box_tc(_id, "%s", %s);'
            % (ORB, node.name, self.tc_expr(t, node))
        )
        w("            }")
        w("        }")
        w("    }")
        w("    return __typeCode;")
        w("}")
        w()
        w("public static String id() {")
        w("    return _id;")
        w("}")
        w()
        w("public static %s read(%s $in) {" % (jtype, IN))
        w(
            "    return (%s) ((org.omg.CORBA_2_3.portable.InputStream) $in)"
            ".read_value(new %sHelper());" % (self.boxed_ref(jtype), name)
        )
        w("}")
        w()
        w("public static void write(%s $out, %s value) {" % (OUT, jtype))
        w(
            "    ((org.omg.CORBA_2_3.portable.OutputStream) $out).write_value(%s, new %sHelper());"
            % ("value", name)
        )
        w("}")
        w()
        w("@Override")
        w("public java.io.Serializable read_value(%s $in) {" % IN)
        w.indent()
        w("%s $result;" % self.jtype(t, node))
        self.read(w, t, "$result", 0, node)
        w("return %s;" % ("new %s($result)" % self.scoped(node) if own else "$result"))
        w.dedent()
        w("}")
        w()
        w("@Override")
        w("public void write_value(%s $out, java.io.Serializable $value) {" % OUT)
        w.indent()
        if own:
            w("%s value = ((%s) $value).value;" % (self.jtype(t, node), self.scoped(node)))
        else:
            w("%s value = (%s) $value;" % (jtype, self.boxed_ref(jtype)))
        self.write(w, t, "value", 0, node)
        w.dedent()
        w("}")
        w()
        w("@Override")
        w("public String get_id() {")
        w("    return _id;")
        w("}")
        w.dedent()
        w("}")
        self.add(node, name + "Helper", w.text())
        self.holder_class(node, jtype)

    def boxed_ref(self, jtype):
        """The reference type a box value of Java type ``jtype`` is cast to."""
        return jtype

    # unions

    def union(self, node):
        name = java_name(node.name)
        disc, cases, default_index = cxx_backend.CxxBackend.union_cases(self, node)
        rdisc = disc.resolved()
        dt = self.jtype(disc, node)
        labels = [l for ls, _, _ in cases for l in ls]
        implicit = cxx_backend.CxxBackend.default_discriminator(self, rdisc, labels)
        implicit = None if implicit is cxx_backend._NONE else implicit
        has_default = default_index >= 0
        scoped = self.scoped(node)

        def lit(label):
            return self.literal(label, disc)

        def cmp(a, b):
            if rdisc.kind == "named" and fe.is_enum(rdisc.node):
                return "%s.value() == %s.value()" % (a, b)
            return "%s == %s" % (a, b)

        w = Writer()
        w("public final class %s implements org.omg.CORBA.portable.IDLEntity {" % name)
        w.indent()
        w("private static final long serialVersionUID = 1L;")
        w()
        w("private %s __discriminator;" % dt)
        w("private boolean __uninitialized = true;")
        for _, m, t in cases:
            w("private %s ___%s;" % (self.jtype(t, node), m))
        w()
        w("public %s() {}" % name)
        w()
        w("public %s discriminator() {" % dt)
        w("    if (__uninitialized) {")
        w("        throw new org.omg.CORBA.BAD_OPERATION();")
        w("    }")
        w("    return __discriminator;")
        w("}")
        all_labels = [lit(l) for l in labels]
        for i, (ls, m, t) in enumerate(cases):
            jt = self.jtype(t, node)
            jm = java_name(m)
            w()
            w("public %s %s() {" % (jt, jm))
            w("    if (__uninitialized) {")
            w("        throw new org.omg.CORBA.BAD_OPERATION();")
            w("    }")
            w("    verify%s(__discriminator);" % m)
            w("    return ___%s;" % m)
            w("}")
            w()
            if i == default_index:
                first = lit(implicit) if implicit is not None else None
                if first is None:
                    raise fe.GeneratorError("no value left for the default member", node)
            else:
                first = lit(ls[0])
            w("public void %s(%s value) {" % (jm, jt))
            w("    __discriminator = %s;" % first)
            w("    ___%s = value;" % m)
            w("    __uninitialized = false;")
            w("}")
            if len(ls) > 1 or i == default_index:
                w()
                w("public void %s(%s discriminator, %s value) {" % (jm, dt, jt))
                w("    verify%s(discriminator);" % m)
                w("    __discriminator = discriminator;")
                w("    ___%s = value;" % m)
                w("    __uninitialized = false;")
                w("}")
            w()
            w("private void verify%s(%s discriminator) {" % (m, dt))
            if i == default_index:
                conds = [cmp("discriminator", l) for l in all_labels]
                if conds:
                    w("    if (%s) {" % " || ".join(conds))
                    w("        throw new org.omg.CORBA.BAD_OPERATION();")
                    w("    }")
            else:
                conds = [cmp("discriminator", lit(l)) for l in ls]
                w("    if (!(%s)) {" % " || ".join(conds))
                w("        throw new org.omg.CORBA.BAD_OPERATION();")
                w("    }")
            w("}")
        if not has_default and implicit is not None:
            w()
            w("public void __default() {")
            w("    __discriminator = %s;" % lit(implicit))
            w("    __uninitialized = false;")
            w("}")
            w()
            w("public void __default(%s discriminator) {" % dt)
            conds = [cmp("discriminator", l) for l in all_labels]
            if conds:
                w("    if (%s) {" % " || ".join(conds))
                w("        throw new org.omg.CORBA.BAD_OPERATION();")
                w("    }")
            w("    __discriminator = discriminator;")
            w("    __uninitialized = false;")
            w("}")
        w.dedent()
        w("}")
        self.add(node, name, w.text())

        def insert_label(w, var, label):
            r = rdisc
            if r.kind == "named" and fe.is_enum(r.node):
                w("%s.insert(%s, %s);" % (self.scoped(r.node, "Helper"), var, lit(label)))
            else:
                w("%s.insert_%s(%s);" % (var, STREAM[r.kind], lit(label)))

        def tc(w):
            w("java.util.List<org.omg.CORBA.UnionMember> $members = new java.util.ArrayList<>();")
            w("org.omg.CORBA.Any $label;")
            for i, (ls, m, t) in enumerate(cases):
                expr = self.tc_expr(t, node)
                for l in ls:
                    w("$label = %s.create_any();" % ORB)
                    insert_label(w, "$label", l)
                    w('$members.add(new org.omg.CORBA.UnionMember("%s", $label, %s, null));' % (m, expr))
                if i == default_index:
                    w("$label = %s.create_any();" % ORB)
                    w("$label.insert_octet((byte) 0);")
                    w('$members.add(new org.omg.CORBA.UnionMember("%s", $label, %s, null));' % (m, expr))
            w(
                '__typeCode = %s.create_union_tc(_id, "%s", %s,'
                % (ORB, node.name, self.tc_expr(disc, node))
            )
            w("        $members.toArray(new org.omg.CORBA.UnionMember[0]));")

        def disc_write(w, expr):
            if rdisc.kind == "named" and fe.is_enum(rdisc.node):
                w("$out.write_ulong(%s.value());" % expr)
            else:
                w("$out.write_%s(%s);" % (STREAM[rdisc.kind], expr))

        def disc_read(w):
            if rdisc.kind == "named" and fe.is_enum(rdisc.node):
                w("%s $d = %s.from_int($in.read_ulong());" % (dt, self.scoped(rdisc.node)))
            else:
                w("%s $d = $in.read_%s();" % (dt, STREAM[rdisc.kind]))

        def case_values(ls):
            if rdisc.kind == "named" and fe.is_enum(rdisc.node):
                return ["%s._%s" % (self.scoped(rdisc.node), java_name(l.name)) for l in ls]
            if rdisc.kind == "boolean":
                return None
            return [lit(l) for l in ls]

        switchable = rdisc.kind != "boolean" and rdisc.kind not in ("longlong", "ulonglong")
        sw_expr = "$d.value()" if rdisc.kind == "named" else "$d"

        def write_body(w):
            disc_write(w, "value.discriminator()")
            if switchable:
                w("switch (%s) {" % ("value.discriminator().value()" if rdisc.kind == "named" else "value.discriminator()"))
                for i, (ls, m, t) in enumerate(cases):
                    if not ls:
                        continue
                    for v in case_values(ls):
                        w("    case %s:" % v)
                    w.level += 2
                    self.write(w, t, "value.%s()" % java_name(m), 0, node)
                    w("break;")
                    w.level -= 2
                w("    default:")
                if has_default:
                    _, m, t = cases[default_index]
                    w.level += 2
                    self.write(w, t, "value.%s()" % java_name(m), 0, node)
                    w.level -= 2
                w("        break;")
                w("}")
            else:
                self.if_chain(w, cases, default_index, "value.discriminator()", lit, cmp,
                              lambda w, i, m, t: self.write(w, t, "value.%s()" % java_name(m), 0, node))

        def read_body(w):
            w("%s $result = new %s();" % (scoped, scoped))
            disc_read(w)

            def read_member(w, m, t, explicit):
                w("%s $v;" % self.jtype(t, node))
                self.read(w, t, "$v", 0, node)
                w("$result.%s(%s$v);" % (java_name(m), "$d, " if explicit else ""))

            if switchable:
                w("switch (%s) {" % sw_expr)
                for i, (ls, m, t) in enumerate(cases):
                    if not ls:
                        continue
                    for v in case_values(ls):
                        w("    case %s:" % v)
                    w("    {")
                    w.level += 2
                    read_member(w, m, t, len(ls) > 1)
                    w("break;")
                    w.level -= 2
                    w("    }")
                w("    default:")
                w.level += 2
                if has_default:
                    _, m, t = cases[default_index]
                    read_member(w, m, t, True)
                else:
                    w("$result.__default($d);")
                w("break;")
                w.level -= 2
                w("}")
            else:
                def body(w, i, m, t):
                    read_member(w, m, t, len(cases[i][0]) > 1 or i == default_index)

                no_default = None
                if not has_default and implicit is not None:
                    no_default = lambda w: w("$result.__default($d);")  # noqa: E731
                self.if_chain(w, cases, default_index, "$d", lit, cmp, body, no_default)
            w("return $result;")

        self.helper(node, scoped, tc, write_body, read_body)
        self.holder_class(node, scoped)
        self.nested(node)

    def if_chain(self, w, cases, default_index, expr, lit, cmp, body, no_default=None):
        """if / else if over the labels (for boolean and 64-bit
        discriminators, which Java cannot switch on)."""
        first = True
        for i, (ls, m, t) in enumerate(cases):
            if not ls:
                continue
            cond = " || ".join(cmp(expr, lit(l)) for l in ls)
            w("%s (%s) {" % ("if" if first else "} else if", cond))
            w.indent()
            body(w, i, m, t)
            w.dedent()
            first = False
        if default_index >= 0:
            _, m, t = cases[default_index]
            if first:
                w("{")
            else:
                w("} else {")
            w.indent()
            body(w, default_index, m, t)
            w.dedent()
            w("}")
        elif no_default is not None:
            if first:
                w("{")
            else:
                w("} else {")
            w.indent()
            no_default(w)
            w.dedent()
            w("}")
        elif not first:
            w("}")

    # interfaces

    def bases(self, node):
        return cxx_backend.CxxBackend.bases(self, node)

    def ancestors(self, node):
        return cxx_backend.CxxBackend.ancestors(self, node)

    def operations(self, node):
        return cxx_backend.CxxBackend.operations(self, node)

    def param_list(self, params, where):
        out = []
        for p, t, direction in params:
            if direction == "in":
                out.append("%s %s" % (self.jtype(t, where), java_name(p)))
            else:
                out.append("%s %s" % (self.holder(t, where), java_name(p)))
        return ", ".join(out)

    def signature(self, method, ret, params, excs, where):
        throws = ""
        if excs:
            throws = " throws " + ", ".join(self.scoped(e) for e in excs)
        return "%s %s(%s)%s" % (
            self.jtype(ret, where),
            java_name(method),
            self.param_list(params, where),
            throws,
        )

    def is_abstract(self, node):
        return bool(getattr(self.full_iface(node), "is_abstract", False))

    def interface(self, node):
        if self.is_abstract(node):
            self.abstract_interface(node)
            return
        name = java_name(node.name)
        bases = [self.full_iface(b) for b in self.bases(node)]
        local = bool(getattr(node, "is_local", False))
        ops = self.operations(node)

        # IOperations: it extends the abstract interfaces the interface
        # inherits, which have no operations interface.
        w = Writer()
        ext = ", ".join(
            self.scoped(b) if self.is_abstract(b) else self.scoped(b, "Operations") for b in bases
        )
        w("public interface %sOperations%s {" % (name, (" extends " + ext) if ext else ""))
        w.indent()
        for opname, method, ret, params, excs, oneway, d in ops:
            if opname.startswith("_set_"):
                t = params[0][1]
                w("void %s(%s value);" % (java_name(method), self.jtype(t, d)))
            else:
                w("%s;" % self.signature(method, ret, params, excs, d))
            w()
        w.dedent()
        w("}")
        self.add(node, name + "Operations", w.text())

        # I
        w = Writer()
        ext = [name + "Operations"]
        concrete = [b for b in bases if not self.is_abstract(b)]
        if concrete:
            ext += [self.scoped(b) for b in concrete]
        else:
            ext.append("org.omg.CORBA.Object")
        ext.append("org.omg.CORBA.portable.IDLEntity")
        w("public interface %s extends %s {" % (name, ", ".join(ext)))
        w.indent()
        for d in fe.members_of(node):
            if fe.is_const(d):
                t = fe.type_of(d.type, d)
                w("%s %s = %s;" % (self.jtype(t, d), java_name(d.name), self.literal(d.value, t)))
        w.dedent()
        w("}")
        self.add(node, name, w.text())

        scoped = self.scoped(node)
        kind = "local_interface" if local else "interface"

        def tc(w):
            w('__typeCode = %s.create_%s_tc(_id, "%s");' % (ORB, kind, node.name))

        def write_body(w):
            w("$out.write_Object(value);")

        def read_body(w):
            w("return unchecked_narrow($in.read_Object());")

        def narrow(w):
            for checked in (True, False):
                w(
                    "public static %s %s(org.omg.CORBA.Object obj) {"
                    % (scoped, "narrow" if checked else "unchecked_narrow")
                )
                w.indent()
                w("if (obj == null) {")
                w("    return null;")
                w("}")
                w("if (obj instanceof %s) {" % scoped)
                w("    return (%s) obj;" % scoped)
                w("}")
                if local:
                    w("throw new org.omg.CORBA.BAD_PARAM();")
                else:
                    if checked:
                        w("if (!obj._is_a(id())) {")
                        w("    throw new org.omg.CORBA.BAD_PARAM();")
                        w("}")
                    stub = ".".join(self.package_of(node) + ("_%sStub" % name,))
                    w("%s $stub = new %s();" % (stub, stub))
                    w(
                        "$stub._set_delegate(((org.omg.CORBA.portable.ObjectImpl) obj)"
                        "._get_delegate());"
                    )
                    w("return $stub;")
                w.dedent()
                w("}")
                if checked:
                    w()

        self.helper(node, scoped, tc, write_body, read_body, extra=narrow)
        self.holder_class(node, scoped)
        if local:
            self.local_base(node)
        else:
            self.stub(node)
            self.skeleton(node)
            self.tie(node)
        self.nested(node)

    def abstract_interface(self, node):
        """An abstract interface: a Java interface with the operations,
        which objects (stubs, _AStub for references received as A) and
        values (of valuetypes that support it) implement."""
        name = java_name(node.name)
        bases = [self.full_iface(b) for b in self.bases(node)]
        w = Writer()
        ext = [self.scoped(b) for b in bases] + ["org.omg.CORBA.portable.IDLEntity"]
        w("public interface %s extends %s {" % (name, ", ".join(ext)))
        w.indent()
        for d in fe.members_of(node):
            if fe.is_const(d):
                t = fe.type_of(d.type, d)
                w("%s %s = %s;" % (self.jtype(t, d), java_name(d.name), self.literal(d.value, t)))
                w()
        for opname, method, ret, params, excs, oneway, d in self.operations(node):
            if opname.startswith("_set_"):
                t = params[0][1]
                w("void %s(%s value);" % (java_name(method), self.jtype(t, d)))
            else:
                w("%s;" % self.signature(method, ret, params, excs, d))
            w()
        w.dedent()
        w("}")
        self.add(node, name, w.text())

        scoped = self.scoped(node)
        stub = ".".join(self.package_of(node) + ("_%sStub" % name,))

        def tc(w):
            w('__typeCode = %s.create_abstract_interface_tc(_id, "%s");' % (ORB, node.name))

        def write_body(w):
            w("((org.omg.CORBA_2_3.portable.OutputStream) $out).write_abstract_interface(value);")

        def read_body(w):
            w(
                "return unchecked_narrow("
                "((org.omg.CORBA_2_3.portable.InputStream) $in).read_abstract_interface());"
            )

        def narrow(w):
            # An object or a value: a reference becomes a stub, a value
            # must implement the interface.
            for checked in (True, False):
                w(
                    "public static %s %s(java.lang.Object obj) {"
                    % (scoped, "narrow" if checked else "unchecked_narrow")
                )
                w.indent()
                w("if (obj == null) {")
                w("    return null;")
                w("}")
                w("if (obj instanceof %s) {" % scoped)
                w("    return (%s) obj;" % scoped)
                w("}")
                w("if (!(obj instanceof org.omg.CORBA.portable.ObjectImpl)) {")
                w("    throw new org.omg.CORBA.BAD_PARAM();")
                w("}")
                if checked:
                    w("if (!((org.omg.CORBA.Object) obj)._is_a(id())) {")
                    w("    throw new org.omg.CORBA.BAD_PARAM();")
                    w("}")
                w("%s $stub = new %s();" % (stub, stub))
                w(
                    "$stub._set_delegate(((org.omg.CORBA.portable.ObjectImpl) obj)"
                    "._get_delegate());"
                )
                w("return $stub;")
                w.dedent()
                w("}")
                if checked:
                    w()

        self.helper(node, scoped, tc, write_body, read_body, extra=narrow)
        self.holder_class(node, scoped)
        self.stub(node)
        self.nested(node)

    def full_iface(self, b):
        if fe.is_forward(b):
            full = fe.full_definition(b)
            return full if full is not None else b
        return b

    def all_operations(self, node):
        """The operations of the interface and of all its bases."""
        ops = []
        for n in [node] + self.ancestors(node):
            ops.extend(self.operations(n))
        return ops

    def ids(self, node):
        return [fe.repository_id(node)] + [fe.repository_id(a) for a in self.ancestors(node)]

    def local_base(self, node):
        name = java_name(node.name)
        w = Writer()
        w(
            "public abstract class _%sLocalBase extends org.omg.CORBA.LocalObject implements %s {"
            % (name, self.scoped(node))
        )
        w.indent()
        w("private static final long serialVersionUID = 1L;")
        w("private static final String[] _type_ids = {%s};" % ", ".join('"%s"' % i for i in self.ids(node)))
        w()
        w("public String[] _ids() {")
        w("    return _type_ids.clone();")
        w("}")
        w.dedent()
        w("}")
        self.add(node, "_%sLocalBase" % name, w.text())

    def stub(self, node):
        name = java_name(node.name)
        w = Writer()
        w(
            "public class _%sStub extends org.omg.CORBA.portable.ObjectImpl implements %s {"
            % (name, self.scoped(node))
        )
        w.indent()
        w("private static final String[] __ids = {%s};" % ", ".join('"%s"' % i for i in self.ids(node)))
        w()
        w("@Override")
        w("public String[] _ids() {")
        w("    return __ids.clone();")
        w("}")
        for opname, method, ret, params, excs, oneway, d in self.all_operations(node):
            w()
            if opname.startswith("_set_"):
                t = params[0][1]
                w("@Override")
                w("public void %s(final %s value) {" % (java_name(method), self.jtype(t, d)))
                params = [("value", t, "in")]
            else:
                sig = self.signature(method, ret, params, excs, d)
                args = self.param_list(params, d)
                finals = ", ".join("final " + a for a in args.split(", ")) if args else ""
                sig = sig.replace("(%s)" % args, "(%s)" % finals, 1)
                w("@Override")
                w("public %s {" % sig)
            w.indent()
            w("final class $Call extends org.rustorb.Call {")
            w.indent()
            if ret.kind != "void":
                w("%s $result;" % self.jtype(ret, d))
                w()
            ins = [(p, t, dr) for p, t, dr in params if dr in ("in", "inout")]
            outs = [(p, t) for p, t, dr in params if dr in ("inout", "out")]
            if ins:
                w("@Override")
                w("public void write(%s $out) {" % OUT)
                w.indent()
                for p, t, dr in ins:
                    expr = java_name(p) + (".value" if dr == "inout" else "")
                    self.write(w, t, expr, 0, d)
                w.dedent()
                w("}")
            if ret.kind != "void" or outs:
                if ins:
                    w()
                w("@Override")
                w("public void read(%s $in) {" % IN)
                w.indent()
                if ret.kind != "void":
                    self.read(w, ret, "$result", 0, d)
                for p, t in outs:
                    self.read(w, t, java_name(p) + ".value", 0, d)
                w.dedent()
                w("}")
            if excs:
                w()
                w("@Override")
                w(
                    "public org.omg.CORBA.UserException readException(String $id, %s $in) {"
                    % IN
                )
                w.indent()
                for e in excs:
                    h = self.scoped(e, "Helper")
                    w("if ($id.equals(%s.id())) {" % h)
                    w("    return %s.read($in);" % h)
                    w("}")
                w("return null;")
                w.dedent()
                w("}")
            w.dedent()
            w("}")
            w("$Call $c = new $Call();")
            w(
                'org.rustorb.Stubs.invoke(this, "%s", %s, $c);'
                % (opname, "true" if oneway else "false")
            )
            if excs:
                w("org.omg.CORBA.UserException $e = $c.userException();")
                for e in excs:
                    w("if ($e instanceof %s) {" % self.scoped(e))
                    w("    throw (%s) $e;" % self.scoped(e))
                    w("}")
            if ret.kind != "void":
                w("return $c.$result;")
            w.dedent()
            w("}")
        w.dedent()
        w("}")
        self.add(node, "_%sStub" % name, w.text())

    def skeleton(self, node):
        name = java_name(node.name)
        ops = self.all_operations(node)
        w = Writer()
        w(
            "public abstract class %sPOA extends org.omg.PortableServer.Servant"
            % name
        )
        w(
            "        implements %s, org.omg.CORBA.portable.InvokeHandler {"
            % self.scoped(node, "Operations")
        )
        w.indent()
        w("private static final java.util.Map<String, Integer> _methods = new java.util.HashMap<>();")
        w()
        w("static {")
        for i, op in enumerate(ops):
            w('    _methods.put("%s", %d);' % (op[0], i))
        w("}")
        w()
        w("private static final String[] __ids = {%s};" % ", ".join('"%s"' % i for i in self.ids(node)))
        w()
        w("@Override")
        w(
            "public String[] _all_interfaces(org.omg.PortableServer.POA poa, byte[] objectId) {"
        )
        w("    return __ids.clone();")
        w("}")
        w()
        w("public %s _this() {" % self.scoped(node))
        w("    return %s.narrow(super._this_object());" % self.scoped(node, "Helper"))
        w("}")
        w()
        w("public %s _this(org.omg.CORBA.ORB orb) {" % self.scoped(node))
        w("    return %s.narrow(super._this_object(orb));" % self.scoped(node, "Helper"))
        w("}")
        w()
        w("@Override")
        w(
            "public %s _invoke(String $method, %s $in, org.omg.CORBA.portable.ResponseHandler $rh) {"
            % (OUT, IN)
        )
        w.indent()
        w("%s $out = null;" % OUT)
        w("Integer $index = _methods.get($method);")
        w("if ($index == null) {")
        # The minor code of the other rustorb bindings for an unknown
        # operation.
        w("    throw new org.omg.CORBA.BAD_OPERATION(0x4f4d0002,")
        w("            org.omg.CORBA.CompletionStatus.COMPLETED_NO);")
        w("}")
        w("switch ($index) {")
        w.indent()
        for i, (opname, method, ret, params, excs, oneway, d) in enumerate(ops):
            w("case %d: {" % i)
            w.indent()
            if opname.startswith("_set_"):
                params = [("value", params[0][1], "in")]
            args = []
            for p, t, dr in params:
                v = "$a_" + p
                if dr == "in":
                    w("%s %s;" % (self.jtype(t, d), v))
                    self.read(w, t, v, 0, d)
                else:
                    h = self.holder(t, d)
                    w("%s %s = new %s();" % (h, v, h))
                    if dr == "inout":
                        self.read(w, t, v + ".value", 0, d)
                args.append(v)
            call = "this.%s(%s)" % (java_name(method), ", ".join(args))
            if excs:
                w("try {")
                w.indent()
            if ret.kind != "void":
                w("%s $result = %s;" % (self.jtype(ret, d), call))
            else:
                w("%s;" % call)
            if not oneway:
                w("$out = $rh.createReply();")
                if ret.kind != "void":
                    self.write(w, ret, "$result", 0, d)
                for p, t, dr in params:
                    if dr in ("inout", "out"):
                        self.write(w, t, "$a_%s.value" % p, 0, d)
            if excs:
                w.dedent()
                for e in excs:
                    w("} catch (%s $ex) {" % self.scoped(e))
                    w("    $out = $rh.createExceptionReply();")
                    w("    %s.write($out, $ex);" % self.scoped(e, "Helper"))
                w("}")
            w("break;")
            w.dedent()
            w("}")
        w("default:")
        w("    throw new org.omg.CORBA.BAD_OPERATION(0, org.omg.CORBA.CompletionStatus.COMPLETED_MAYBE);")
        w.dedent()
        w("}")
        w("return $out;")
        w.dedent()
        w("}")
        w.dedent()
        w("}")
        self.add(node, name + "POA", w.text())

    def tie(self, node):
        name = java_name(node.name)
        ops_iface = self.scoped(node, "Operations")
        w = Writer()
        w("public class %sPOATie extends %sPOA {" % (name, name))
        w.indent()
        w("private %s _impl;" % ops_iface)
        w("private org.omg.PortableServer.POA _poa;")
        w()
        w("public %sPOATie(%s delegate) {" % (name, ops_iface))
        w("    _impl = delegate;")
        w("}")
        w()
        w("public %sPOATie(%s delegate, org.omg.PortableServer.POA poa) {" % (name, ops_iface))
        w("    _impl = delegate;")
        w("    _poa = poa;")
        w("}")
        w()
        w("public %s _delegate() {" % ops_iface)
        w("    return _impl;")
        w("}")
        w()
        w("public void _delegate(%s delegate) {" % ops_iface)
        w("    _impl = delegate;")
        w("}")
        w()
        w("@Override")
        w("public org.omg.PortableServer.POA _default_POA() {")
        w("    return _poa != null ? _poa : super._default_POA();")
        w("}")
        for opname, method, ret, params, excs, oneway, d in self.all_operations(node):
            w()
            w("@Override")
            if opname.startswith("_set_"):
                t = params[0][1]
                w("public void %s(%s value) {" % (java_name(method), self.jtype(t, d)))
                w("    _impl.%s(value);" % java_name(method))
            else:
                w("public %s {" % self.signature(method, ret, params, excs, d))
                call = "_impl.%s(%s)" % (java_name(method), ", ".join(java_name(p) for p, _, _ in params))
                w("    %s%s;" % ("return " if ret.kind != "void" else "", call))
            w("}")
        w.dedent()
        w("}")
        self.add(node, name + "POATie", w.text())


def _escape(c, quote):
    o = ord(c)
    if c == quote:
        return "\\" + c
    if c == "\\":
        return "\\\\"
    if 0x20 <= o < 0x7F:
        return c
    if o < 0x10000:
        return "\\u%04x" % o
    o -= 0x10000
    return "\\u%04x\\u%04x" % (0xD800 + (o >> 10), 0xDC00 + (o & 0x3FF))


def write_outputs(backend, outdir):
    """Write every class of the IDL file of ``backend`` under ``outdir``
    (in the directories of their packages); return the paths written."""
    written = []
    for (pkg, name), text in sorted(backend.generate().items()):
        d = os.path.join(outdir, *pkg)
        os.makedirs(d, exist_ok=True)
        path = os.path.join(d, name + ".java")
        tmp = path + ".tmp"
        with open(tmp, "w") as f:
            f.write(text)
        os.replace(tmp, path)
        written.append(path)
    return written
