"""The Python backend: ``rustorb-idl -bpython``.

For ``Foo.idl`` it writes, like ``omniidl -bpython``:

- ``Foo_idl.py``: every definition of the file;
- ``Module/__init__.py`` for each IDL module (sub-packages for nested
  modules), which imports the ``*_idl.py`` files that define names in the
  module;
- ``Module__POA/__init__.py`` with the skeleton classes;
- ``_GlobalIDL`` / ``_GlobalIDL__POA`` for definitions outside modules;
- ``__init__.pyi`` type stubs next to each ``__init__.py``.

The generated code uses only :mod:`rustorb._rt`, :mod:`rustorb.CORBA` and
:mod:`rustorb.PortableServer`; see ``rustorb/_rt.py`` for what each call
does. Runtime modules and helper names are imported with a ``_0_`` prefix,
which no IDL identifier can have, so that IDL names never hide them.
"""

import os

from . import frontend as fe
from .names import module_of_file, py_name

#: Must match rustorb._rt.GENERATED_CODE_VERSION.
GENERATED_CODE_VERSION = 1

HEADER = (
    "# Generated by rustorb-idl from %s. Do not edit.\n"
    "#\n"
    "# This file is not covered by the license of rustorb-idl.\n"
)

INT_RANGES = {
    "short": (-(1 << 15), (1 << 15) - 1),
    "long": (-(1 << 31), (1 << 31) - 1),
    "longlong": (-(1 << 63), (1 << 63) - 1),
    "ushort": (0, (1 << 16) - 1),
    "ulong": (0, (1 << 32) - 1),
    "ulonglong": (0, (1 << 64) - 1),
    "octet": (0, 255),
}

TC_BASIC = {
    "short": "TC_short",
    "long": "TC_long",
    "ushort": "TC_ushort",
    "ulong": "TC_ulong",
    "longlong": "TC_longlong",
    "ulonglong": "TC_ulonglong",
    "float": "TC_float",
    "double": "TC_double",
    "longdouble": "TC_longdouble",
    "boolean": "TC_boolean",
    "char": "TC_char",
    "wchar": "TC_wchar",
    "octet": "TC_octet",
    "any": "TC_any",
    "Object": "TC_Object",
    "TypeCode": "TC_TypeCode",
    "Principal": "TC_Principal",
}


def py_tuple(items):
    """A Python tuple expression: ``()``, ``(a,)``, ``(a, b)``."""
    items = list(items)
    if len(items) == 1:
        return "(%s,)" % items[0]
    return "(%s)" % ", ".join(items)


class Writer(object):
    def __init__(self):
        self.lines = []
        self.level = 0

    def __call__(self, text=""):
        if text:
            self.lines.append("    " * self.level + text)
        else:
            self.lines.append("")

    def indent(self):
        self.level += 1

    def dedent(self):
        self.level -= 1

    def text(self):
        return "\n".join(self.lines) + "\n"


class Options(object):
    def __init__(self, global_module="_GlobalIDL", stubs=True, package=""):
        self.global_module = global_module
        self.stubs = stubs
        # Python package to put everything in (omniidl's -Wbpackage)
        self.package = package


class PythonBackend(object):
    def __init__(self, spec, options=None):
        self.spec = spec
        self.opt = options or Options()
        self.idl_name = os.path.basename(spec.path)
        self.file_module = module_of_file(spec.path)
        self._modvars = {}

    # -- names -----------------------------------------------------------

    def in_package(self, name):
        """``name`` inside the package of ``-Wbpackage``."""
        return self.opt.package + "." + name if self.opt.package else name

    def py_module(self, modules):
        """Python module name of an IDL module (a tuple of names)."""
        if not modules:
            return self.in_package(self.opt.global_module)
        return self.in_package(".".join(py_name(m) for m in modules))

    def poa_module(self, modules):
        if not modules:
            return self.in_package(self.opt.global_module + "__POA")
        return self.in_package(
            py_name(modules[0]) + "__POA" + "".join("." + py_name(m) for m in modules[1:])
        )

    def modvar(self, pymod):
        """The variable of a ``*_idl.py`` file that holds a module object."""
        v = self._modvars.get(pymod)
        if v is None:
            v = "_0_" + pymod.replace(".", "__")
            while v in self._modvars.values():
                v += "_"
            self._modvars[pymod] = v
        return v

    def container(self, node):
        """Expression for the scope (module object or class) a definition
        is in."""
        expr = self.modvar(self.py_module(fe.enclosing_modules(node)))
        for n in fe.inner_scope(node):
            expr += "." + py_name(n)
        return expr

    def ref(self, node):
        """Expression for the Python object of a definition."""
        return self.container(node) + "." + py_name(node.name)

    def tc_ref(self, node):
        return self.container(node) + "._tc_" + node.name

    def qualname(self, node):
        return ".".join([py_name(n) for n in fe.inner_scope(node)] + [py_name(node.name)])

    # -- types -----------------------------------------------------------

    def tc(self, t):
        """Expression for the TypeCode of a :class:`frontend.Type`."""
        k = t.kind
        if k in TC_BASIC:
            return "_0_CORBA." + TC_BASIC[k]
        if k in ("string", "wstring"):
            if t.bound:
                return "_0_rt.tc_%s(%d)" % (k, t.bound)
            return "_0_CORBA.TC_" + k
        if k == "sequence":
            return "_0_rt.tc_sequence(%s, %d)" % (self.tc(t.content), t.bound)
        if k == "array":
            return "_0_rt.tc_array(%s, %d)" % (self.tc(t.content), t.length)
        if k == "fixed":
            return "_0_rt.tc_fixed(%d, %d)" % (t.digits, t.scale)
        if k == "named":
            return self.tc_ref(t.node)
        raise fe.GeneratorError("no TypeCode for %r" % t)

    # -- values ----------------------------------------------------------

    def literal(self, value, t):
        """A Python expression for a constant value of type ``t``."""
        r = t.resolved()
        if r.kind == "named" and fe.is_enum(r.node):
            return self.enumerator_ref(value)
        if r.kind == "fixed":
            return '_0_CORBA.fixed("%s")' % value
        if r.kind == "boolean":
            return "True" if value else "False"
        if r.kind in ("float", "double", "longdouble"):
            v = float(value)
            if v != v:
                return 'float("nan")'
            if v in (float("inf"), float("-inf")):
                return 'float("%s")' % ("inf" if v > 0 else "-inf")
            return repr(v)
        if isinstance(value, bool):
            return repr(int(value))
        return repr(value)

    def enumerator_ref(self, item):
        """Expression for an enumerator (an IDLEnumValue): enumerators are
        names in the scope of their enum."""
        enum = item.parent
        return self.container(enum) + "." + py_name(item.name)

    # -- the *_idl.py file -------------------------------------------------

    def generate_stub_module(self):
        w = Writer()
        self.w = w
        body = Writer()
        self.w = body
        for it in fe.definitions(self.spec):
            self.definition(it.node)
        self.w = w

        w(HEADER % self.idl_name)
        w('"""Definitions of %s."""' % self.idl_name)
        w()
        w("import rustorb._rt as _0_rt")
        w("from rustorb import CORBA as _0_CORBA")
        w("from rustorb import PortableServer as _0_PortableServer")
        w()
        w("_0_rt.check_version(%d)" % GENERATED_CODE_VERSION)
        w()
        included = self.spec.included_files()
        if included:
            w("# Files included by %s" % self.idl_name)
            for f in included:
                w("import %s  # %s" % (self.in_package(module_of_file(f)), os.path.basename(f)))
            w()
        for pymod, var in sorted(self._modvars.items(), key=lambda kv: kv[0]):
            w('%s = _0_rt.open_module("%s", __file__)' % (var, pymod))
        w()
        w.lines.extend(body.lines)
        return w.text()

    def definition(self, node):
        if fe.is_module(node):
            return
        # Make sure the module variables exist even for empty scopes.
        mods = fe.enclosing_modules(node)
        self.modvar(self.py_module(mods))
        if fe.is_interface(node):
            self.modvar(self.poa_module(mods))
        if fe.is_const(node):
            self.const(node)
        elif fe.is_enum(node):
            self.enum(node)
        elif fe.is_typedef(node):
            self.typedef(node)
        elif fe.is_exception(node):
            self.struct(node, exception=True)
        elif fe.is_struct(node):
            if fe.is_forward(node):
                self.forward_struct(node, "declare_struct")
            else:
                self.struct(node)
        elif fe.is_union(node):
            if fe.is_forward(node):
                self.forward_struct(node, "declare_union")
            else:
                self.union(node)
        elif fe.is_interface(node):
            if fe.is_forward(node):
                self.forward_interface(node)
            else:
                self.interface(node)
        elif fe.is_valuetype(node):
            if fe.is_forward(node):
                self.forward_value(node)
            elif node.is_boxed:
                self.value_box(node)
            else:
                self.valuetype(node)
        elif fe.is_native(node):
            self.w("# native %s" % node.name)
            self.w(
                '%s = _0_rt.tc_native("%s", "%s")'
                % (self.tc_ref(node), fe.repository_id(node), node.name)
            )
            self.w()
        elif fe.is_operation(node) or fe.is_attribute(node):
            pass  # written with the interface
        else:
            raise fe.GeneratorError(
                "%s definitions are not supported yet" % fe.kind_name(node), node
            )

    def nested(self, scope):
        for d in fe.members_of(scope):
            if fe.is_operation(d) or fe.is_attribute(d):
                continue
            if (
                fe.is_struct(d)
                or fe.is_union(d)
                or fe.is_exception(d)
                or fe.is_enum(d)
                or fe.is_typedef(d)
                or fe.is_const(d)
                or fe.is_native(d)
            ):
                self.definition(d)

    def class_header(self, node, bases, pymodule=None):
        w = self.w
        w("class %s(%s):" % (py_name(node.name), ", ".join(bases)))
        w.indent()
        w('__module__ = "%s"' % (pymodule or self.py_module(fe.enclosing_modules(node))))
        w('__qualname__ = "%s"' % self.qualname(node))
        w('_NP_RepositoryId = "%s"' % fe.repository_id(node))

    def assign_class(self, node, target=None):
        w = self.w
        w.dedent()
        w()
        w("%s = %s" % (target or self.ref(node), py_name(node.name)))
        w("del %s" % py_name(node.name))

    def const(self, node):
        t = fe.type_of(node.type, node)
        self.w("# const %s" % node.name)
        self.w("%s = %s" % (self.ref(node), self.literal(node.value, t)))
        self.w()

    def enum(self, node):
        w = self.w
        rid = fe.repository_id(node)
        names = [v.name for v in node.values]
        w("# enum %s" % node.name)
        w('%s = _0_rt.Enum("%s", %s)' % (self.ref(node), rid, py_tuple('"%s"' % n for n in names)))
        for i, n in enumerate(names):
            w("%s.%s = %s._item(%d)" % (self.container(node), py_name(n), self.ref(node), i))
        w(
            '%s = _0_rt.tc_enum("%s", "%s", %s)'
            % (self.tc_ref(node), rid, node.name, self.ref(node))
        )
        w()

    def typedef(self, node):
        w = self.w
        t = fe.type_of(node.type, node)
        r = t.resolved()
        if r.kind == "named" and (fe.is_struct(r.node) or fe.is_union(r.node)):
            base = self.ref(t.node)  # a typedef of a struct is a subclass of it
        else:
            base = "_0_rt.Typedef"
        w("# typedef %s" % node.name)
        self.class_header(node, [base])
        self.assign_class(node)
        w(
            '%s = _0_rt.tc_alias("%s", "%s", %s)'
            % (self.tc_ref(node), fe.repository_id(node), node.name, self.tc(t))
        )
        w()

    def forward_struct(self, node, declare):
        self.w("# forward declaration of %s" % node.name)
        self.w(
            '%s = _0_rt.%s("%s", "%s")'
            % (self.tc_ref(node), declare, fe.repository_id(node), node.name)
        )
        self.w()

    def struct(self, node, exception=False):
        w = self.w
        rid = fe.repository_id(node)
        members = [(m.name, fe.type_of(m.type, m)) for m in node.members]
        if getattr(node, "base", None) is not None:
            raise fe.GeneratorError("struct inheritance is not supported", node)
        args = [py_name(m) for m, _ in members]
        w("# %s %s" % ("exception" if exception else "struct", node.name))
        w(
            '%s = _0_rt.%s("%s", "%s")'
            % (
                self.tc_ref(node),
                "declare_except" if exception else "declare_struct",
                rid,
                node.name,
            )
        )
        self.class_header(node, ["_0_CORBA.UserException" if exception else "_0_rt.Struct"])
        w("_NP_members = %s" % py_tuple('"%s"' % a for a in args))
        w()
        w(
            "def __init__(%s):" % ", ".join(["self"] + args)
            if "self" not in args
            else "def __init__(%s):" % ", ".join(["_0_self"] + args)
        )
        w.indent()
        me = "self" if "self" not in args else "_0_self"
        if exception:
            w("_0_CORBA.UserException.__init__(%s)" % ", ".join([me] + args))
        else:
            for a in args:
                w("%s.%s = %s" % (me, a, a))
            if not args:
                w("pass")
        w.dedent()
        self.assign_class(node)
        w()
        self.nested(node)
        w(
            "_0_rt.%s(%s, %s, [%s])"
            % (
                "define_except" if exception else "define_struct",
                self.tc_ref(node),
                self.ref(node),
                ", ".join('("%s", %s)' % (m, self.tc(t)) for m, t in members),
            )
        )
        w()

    # -- unions ----------------------------------------------------------

    def union(self, node):
        w = self.w
        rid = fe.repository_id(node)
        disc = fe.type_of(node.discriminator_type, node)
        rdisc = disc.resolved()
        cases = []  # (label value or None for default, member name, Type)
        default_index = -1
        default_member = None
        for m in node.members:
            t = fe.type_of(m.type, m)
            for label in m.labels:
                cases.append((label, m.name, t))
            if m.is_default:
                default_index = len(cases)
                default_member = m.name
                cases.append((None, m.name, t))
        labels = [c[0] for c in cases if c[0] is not None]

        d_to_m = []
        m_to_d = {}
        order = []
        for label, name, _ in cases:
            if label is None:
                continue
            d_to_m.append((self.literal(label, disc), py_name(name)))
            if name not in m_to_d:
                order.append(name)
            m_to_d[name] = label  # the last label, as omniORBpy does
        def_d = self.default_discriminator(rdisc, labels)

        w("# union %s" % node.name)
        w('%s = _0_rt.declare_union("%s", "%s")' % (self.tc_ref(node), rid, node.name))
        self.class_header(node, ["_0_rt.Union"])
        w("_d_to_m = {%s}" % ", ".join('%s: "%s"' % kv for kv in d_to_m))
        w(
            "_m_to_d = {%s}"
            % ", ".join('"%s": %s' % (py_name(n), self.literal(m_to_d[n], disc)) for n in order)
        )
        w("_def_m = %s" % ('"%s"' % py_name(default_member) if default_member else "None"))
        w(
            "_def_d = %s"
            % (self.literal(def_d, disc) if def_d is not _NONE else "_0_rt._NO_DEFAULT")
        )
        self.assign_class(node)
        w()
        self.nested(node)
        w(
            "_0_rt.define_union(%s, %s, %s, [%s], %d)"
            % (
                self.tc_ref(node),
                self.ref(node),
                self.tc(disc),
                ", ".join(
                    '(%s, "%s", %s)'
                    % ("None" if label is None else self.literal(label, disc), name, self.tc(t))
                    for label, name, t in cases
                ),
                default_index,
            )
        )
        w()

    def default_discriminator(self, disc, labels):
        """The discriminator value of a union that holds its ``default``
        member, or that holds no member: the first value of the
        discriminator type, in order, that no label uses (for an integer
        type, counting up from its smallest value)."""
        k = disc.kind
        used = set()
        for label in labels:
            if hasattr(label, "name") and hasattr(label, "parent"):
                used.add(label.name)
            else:
                used.add(label)
        if k in INT_RANGES:
            lo, hi = INT_RANGES[k]
            v = lo
            while v in used and v <= hi:
                v += 1
            return v if v <= hi else _NONE
        if k == "boolean":
            for v in (False, True):
                if v not in used:
                    return v
            return _NONE
        if k in ("char", "wchar"):
            for c in range(0, 256 if k == "char" else 0x10000):
                if chr(c) not in used:
                    return chr(c)
            return _NONE
        if k == "named" and fe.is_enum(disc.node):
            for v in disc.node.values:
                if v.name not in used:
                    return v
            return _NONE
        raise fe.GeneratorError("unsupported union discriminator type %r" % disc)

    # -- valuetypes ------------------------------------------------------

    def forward_value(self, node):
        self.w("# forward declaration of valuetype %s" % node.name)
        self.w(
            '%s = _0_rt.declare_value("%s", "%s")'
            % (self.tc_ref(node), fe.repository_id(node), node.name)
        )
        self.w()

    def value_box(self, node):
        # The value of a box is the boxed value itself (None for null);
        # the class only names the type.
        w = self.w
        t = fe.type_of(node.boxed_type, node)
        w("# valuetype %s (boxed)" % node.name)
        self.class_header(node, ["_0_rt.Typedef"])
        self.assign_class(node)
        w(
            '%s = _0_rt.tc_value_box("%s", "%s", %s)'
            % (self.tc_ref(node), fe.repository_id(node), node.name, self.tc(t))
        )
        w()

    def valuetype(self, node):
        w = self.w
        if node.supports:
            raise fe.GeneratorError("valuetypes that support interfaces are not supported yet", node)
        bases = fe.value_bases(node)
        base = fe.concrete_base(node)
        if node.is_abstract:
            modifier = "VM_ABSTRACT"
        elif node.is_custom:
            modifier = "VM_CUSTOM"
        elif node.is_truncatable:
            modifier = "VM_TRUNCATABLE"
        else:
            modifier = "VM_NONE"
        members = [(m.name, fe.type_of(m.type, m), m.is_public) for m in node.state_members]
        w("# valuetype %s" % node.name)
        w(
            '%s = _0_rt.declare_value("%s", "%s")'
            % (self.tc_ref(node), fe.repository_id(node), node.name)
        )
        cls_bases = [self.ref(b) for b in bases] or ["_0_CORBA.ValueBase"]
        if node.is_custom:
            cls_bases.append("_0_CORBA.CustomMarshal")
        self.class_header(node, cls_bases)
        names = [py_name(n) for n in fe.state_member_names(node)]
        w("_NP_members = %s" % py_tuple('"%s"' % n for n in names))
        self.assign_class(node)
        w()
        self.nested(node)
        w(
            "_0_rt.define_value(%s, %s, _0_CORBA.%s, %s, [%s])"
            % (
                self.tc_ref(node),
                self.ref(node),
                modifier,
                self.tc_ref(base) if base is not None else "None",
                ", ".join(
                    '("%s", %s, _0_CORBA.%s)'
                    % (n, self.tc(t), "PUBLIC_MEMBER" if public else "PRIVATE_MEMBER")
                    for n, t, public in members
                ),
            )
        )
        # A valuetype with operations or initializers needs an
        # implementation, which the application registers a factory for.
        # So does a custom one, for marshal and unmarshal.
        own_factory = not node.is_abstract and not node.is_custom and not fe.has_behaviour(node)
        w("_0_rt.register_value(%s%s)" % (self.tc_ref(node), "" if own_factory else ", False"))
        w()

    # -- interfaces ------------------------------------------------------

    def interface_tc_call(self, node):
        if node.is_abstract:
            return "tc_abstract_interface"
        if node.is_local:
            return "tc_local_interface"
        return "tc_objref"

    def forward_interface(self, node):
        self.w("# forward declaration of interface %s" % node.name)
        self.w(
            '%s = _0_rt.%s("%s", "%s")'
            % (self.tc_ref(node), self.interface_tc_call(node), fe.repository_id(node), node.name)
        )
        self.w()

    def bases(self, node):
        return [b if fe.is_interface(b) else b.obj for b in node.inheritances]

    def interface(self, node):
        w = self.w
        rid = fe.repository_id(node)
        mods = fe.enclosing_modules(node)
        bases = self.bases(node)
        w("# interface %s" % node.name)
        w(
            '%s = _0_rt.%s("%s", "%s")'
            % (self.tc_ref(node), self.interface_tc_call(node), rid, node.name)
        )
        self.class_header(node, [self.ref(b) for b in bases] or ["object"])
        w("_nil = None")
        w()
        w("def __init__(self, *args, **kw):")
        w('    raise RuntimeError("Cannot construct objects of this type.")')
        self.assign_class(node)
        w()
        self.nested(node)

        # operations
        ops = self.operations(node)
        w("%s._NP_operations = {" % self.ref(node))
        w.indent()
        for name, op_expr, _ in ops:
            w('"%s": %s,' % (name, op_expr))
        w.dedent()
        w("}")
        w()

        # stub
        objref = "_objref_" + node.name
        w(
            "class %s(%s):"
            % (
                objref,
                ", ".join(
                    [self.container(b) + "._objref_" + b.name for b in bases] or ["_0_CORBA.Object"]
                ),
            )
        )
        w.indent()
        w('__module__ = "%s"' % self.py_module(mods))
        w('__qualname__ = "%s"' % objref)
        w("_NP_RepositoryId = %s._NP_RepositoryId" % self.ref(node))
        w("_NP_operations = %s._NP_operations" % self.ref(node))
        w()
        w("def __init__(self, obj):")
        w("    _0_CORBA.Object.__init__(self, obj)")
        attrs = []
        for name, _, params in ops:
            me = "self" if "self" not in params else "_0_self"
            w()
            w(
                "def %s(%s):"
                % (py_name(name) if not name.startswith("_") else name, ", ".join([me] + params))
            )
            w(
                '    return %s._invoke(%s._NP_operations["%s"], %s)'
                % (me, self.ref(node), name, py_tuple(params))
            )
        for a in fe.members_of(node):
            if fe.is_attribute(a):
                attrs.append(a)
        for a in attrs:
            pn = py_name(a.name)
            w()
            if a.readonly:
                w("%s = property(_get_%s)" % (pn, a.name))
            else:
                w("%s = property(_get_%s, _set_%s)" % (pn, a.name, a.name))
        w.dedent()
        w()
        w("%s.%s = %s" % (self.container(node), objref, objref))
        w("_0_rt.register_interface(%s, %s)" % (self.ref(node), objref))
        w("del %s" % objref)
        w()

        # skeleton
        poa = self.modvar(self.poa_module(mods))
        w(
            "class %s(%s):"
            % (
                py_name(node.name),
                ", ".join(
                    [
                        self.modvar(self.poa_module(fe.enclosing_modules(b)))
                        + "."
                        + py_name(b.name)
                        for b in bases
                    ]
                    or ["_0_PortableServer.Servant"]
                ),
            )
        )
        w.indent()
        w('__module__ = "%s"' % self.poa_module(mods))
        w('__qualname__ = "%s"' % py_name(node.name))
        w("_NP_RepositoryId = %s._NP_RepositoryId" % self.ref(node))
        w("_NP_operations = %s._NP_operations" % self.ref(node))
        w.dedent()
        w()
        w("%s.%s = %s" % (poa, py_name(node.name), py_name(node.name)))
        w("_0_rt.register_skeleton(%s)" % py_name(node.name))
        w("del %s" % py_name(node.name))
        w()

    def operations(self, node):
        """``[(name, Operation expression, Python parameter names)]`` for
        the operations and attribute accessors of an interface, in order."""
        ops = []
        for d in fe.members_of(node):
            if fe.is_operation(d):
                ins, outs = [], []
                ret = fe.type_of(d.returns, d)
                if ret.kind != "void":
                    outs.append(self.tc(ret))
                params = []
                for a in d.arguments:
                    t = self.tc(fe.type_of(a.type, a))
                    if a.direction in ("in", "inout"):
                        ins.append(t)
                        params.append(py_name(a.name))
                    if a.direction in ("out", "inout"):
                        outs.append(t)
                excs = [self.tc_ref(e) for e in fe.raised_exceptions(d)]
                ctx = list(getattr(d, "contexts", []) or [])
                ops.append((d.name, self.op_expr(d.name, ins, outs, excs, d.oneway, ctx), params))
            elif fe.is_attribute(d):
                t = self.tc(fe.type_of(d.type, d))
                get_ex = [self.tc_ref(e) for e in _resolve_exceptions(d, d.getraises)]
                ops.append(
                    (
                        "_get_" + d.name,
                        self.op_expr("_get_" + d.name, [], [t], get_ex, False, []),
                        [],
                    )
                )
                if not d.readonly:
                    set_ex = [self.tc_ref(e) for e in _resolve_exceptions(d, d.setraises)]
                    ops.append(
                        (
                            "_set_" + d.name,
                            self.op_expr("_set_" + d.name, [t], [], set_ex, False, []),
                            ["value"],
                        )
                    )
        return ops

    def op_expr(self, name, ins, outs, excs, oneway, contexts):
        tup = py_tuple
        args = ['"%s"' % name, tup(ins), tup(outs), tup(excs)]
        if oneway or contexts:
            args.append("True" if oneway else "False")
        if contexts:
            args.append(tup(['"%s"' % c for c in contexts]))
        return "_0_rt.Operation(%s)" % ", ".join(args)

    # -- packages --------------------------------------------------------

    def packages(self):
        """``[(Python package name, is POA package)]`` to write."""
        mods = fe.modules(self.spec)
        out = []
        globals_ = any(not it.modules for it in fe.definitions(self.spec))
        if globals_:
            out.append(((), False))
            out.append(((), True))
        for m in mods:
            out.append((m, False))
            out.append((m, True))
        return out

    def package_name(self, modules, poa):
        return self.poa_module(modules) if poa else self.py_module(modules)

    def sub_packages(self, modules, poa):
        """Direct sub-modules of ``modules`` this file defines something in."""
        if not modules:
            return []
        subs = []
        for m in fe.modules(self.spec):
            if len(m) == len(modules) + 1 and m[:-1] == modules:
                subs.append(py_name(m[-1]))
        return subs


_NONE = object()


def _resolve_exceptions(node, names):
    out = []
    for n in names or []:
        if hasattr(n, "repository_id"):
            out.append(n)
            continue
        found = (
            node.root_node.find_exceptions(str(n), scope=node)
            if hasattr(node.root_node, "find_exceptions")
            else []
        )
        if not found:
            raise fe.GeneratorError("Can not find the exception %s" % n, node)
        out.append(found[0])
    return out


