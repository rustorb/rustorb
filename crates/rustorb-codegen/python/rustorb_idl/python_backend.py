# Package __init__.py files, shared by the IDL files that define names in a
# module: each run adds its file to the lists between the markers.

FILES_MARK = "# rustorb-idl: files"
SUBS_MARK = "# rustorb-idl: sub-modules"
END_MARK = "# rustorb-idl: end"


_SUB_PREFIX = '_0_importlib.import_module(__name__ + ".'
_SUB_SUFFIX = '")'


def _read_lists(path):
    files, subs = [], []
    if not os.path.exists(path):
        return files, subs
    with open(path) as f:
        lines = f.read().splitlines()
    if FILES_MARK not in lines:
        raise fe.GeneratorError(
            "%s exists but was not written by rustorb-idl; remove it first" % path
        )
    section = None
    for line in lines:
        if line == FILES_MARK:
            section = files
        elif line == SUBS_MARK:
            section = subs
        elif line == END_MARK:
            section = None
        elif section is files and line.startswith("import "):
            files.append(line[len("import ") :].strip())
        elif section is subs and line.startswith(_SUB_PREFIX) and line.endswith(_SUB_SUFFIX):
            subs.append(line[len(_SUB_PREFIX) : -len(_SUB_SUFFIX)])
    return files, subs


def package_init(path, idl_module, file_module, subs):
    """The ``__init__.py`` of the package of the IDL module ``idl_module``
    (``A::B``), which imports ``file_module`` (a full module name) among
    the files already listed."""
    files, old_subs = _read_lists(path)
    if file_module not in files:
        files.append(file_module)
    for s in subs:
        if s not in old_subs:
            old_subs.append(s)
    w = Writer()
    w("# Generated by rustorb-idl. Do not edit.")
    w("#")
    w("# This file is not covered by the license of rustorb-idl.")
    w()
    w('"""IDL module %s."""' % idl_module)
    w()
    w("import importlib as _0_importlib")
    w("import sys as _0_sys")
    w()
    w("import rustorb._rt as _0_rt")
    w()
    w("_0_rt.bind_package(_0_sys.modules[__name__])")
    w()
    # sub-packages first, so that the *_idl.py files find every package of
    # the module tree already bound
    w(SUBS_MARK)
    for s in old_subs:
        w(_SUB_PREFIX + s + _SUB_SUFFIX)
    w(FILES_MARK)
    for f in files:
        w("import %s" % f)
    w(END_MARK)
    return w.text()


def write_outputs(backend, outdir):
    """Write every file for the IDL file of ``backend`` under ``outdir``;
    return the paths written."""
    written = []
    stub_text = backend.generate_stub_module()
    top = outdir
    if backend.opt.package:
        # the packages of -Wbpackage (an existing __init__.py is kept)
        for part in backend.opt.package.split("."):
            top = os.path.join(top, part)
            os.makedirs(top, exist_ok=True)
            init = os.path.join(top, "__init__.py")
            if not os.path.exists(init):
                _write(init, "")
                written.append(init)
    path = os.path.join(top, backend.file_module + ".py")
    _write(path, stub_text)
    written.append(path)
    file_module = backend.in_package(backend.file_module)
    for modules, poa in backend.packages():
        pkg = backend.package_name(modules, poa)
        d = os.path.join(outdir, *pkg.split("."))
        os.makedirs(d, exist_ok=True)
        init = os.path.join(d, "__init__.py")
        idl_module = "::".join(modules) or backend.opt.global_module
        text = package_init(init, idl_module, file_module, backend.sub_packages(modules, poa))
        _write(init, text)
        written.append(init)
        if backend.opt.stubs:
            from . import pyi

            pyi_path = os.path.join(d, "__init__.pyi")
            _write(pyi_path, pyi.package_stub(backend, modules, poa, pyi_path))
            written.append(pyi_path)
    return written


def _write(path, text):
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        f.write(text)
    os.replace(tmp, path)
