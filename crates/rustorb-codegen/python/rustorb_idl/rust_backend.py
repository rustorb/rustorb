"""The Rust backend: ``rustorb-idl -brust``.

Writes one Rust source file per IDL file (``InteropTest.idl`` ->
``interop_test.rs``), following the mapping of ``docs/rust-mapping.md``:

- IDL modules are ``pub mod`` (snake_case); the definitions inside an
  interface, struct, union, exception or valuetype ``X`` are in the module
  ``x`` next to it, with the error types of the operations of an
  interface;
- structs and exceptions are structs, enums are enums, unions are enums
  with a variant per member; typedefs are ``type`` aliases, with a
  descriptor of the same name in the ``alias`` module of their scope;
- an interface ``I`` is the reference type ``I``, the servant trait
  ``IServant`` and the skeleton ``IPoa<T>``;
- a valuetype ``V`` is the handle ``V`` and its state ``VState``; a value
  box is a struct around an ``Arc`` of its content. The application
  implements ``CustomMarshal`` for the state of a custom valuetype, and
  the trait ``VOperations`` for that of a valuetype with operations or
  supported interfaces (whose servant traits the handle implements).

Every named type implements ``rustorb_core::idl::IdlType``. The code refers
to the core only by absolute paths (``::rustorb_core`` or ``-Wbcore``), and
to other definitions by paths relative to where it is (``super::...``), so
that the file can be included anywhere. The output is passed through
``rustfmt`` when it is found.

Definitions of included files are written as well, except those in the
modules mapped with ``-Wbextern=MODULE=PATH``, which are referred to under
``PATH``.
"""

